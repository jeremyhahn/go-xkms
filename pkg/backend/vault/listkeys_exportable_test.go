// findListedByCN returns the ListKeys entry for cn, failing the test if
// ListKeys did not report it.
func findListedByCN(t *testing.T, listed []*types.KeyAttributes, cn string) *types.KeyAttributes {
	t.Helper()
	for _, ka := range listed {
		if ka.CN == cn {
			return ka
		}
	}
	t.Fatalf("ListKeys did not report %q", cn)
	return nil
}

// TestListKeys_SymmetricKeyRoundTripsExportableTrue is the success case for
// go-xkms#932: a symmetric key created with Exportable: true must round-trip
// through ListKeys as Exportable=true, and ExportKeyMaterial -- Vault
// Transit's genuine export endpoint for a key created exportable (see
// vault_importexport.go) -- must actually succeed using the round-tripped
// attributes, the same way pkg/xkms's findKeyAttrs/loadStoredKeyAttrs would
// use them.
//
// Before this fix, GenerateSymmetricKey's metadata record already carried
// "exportable" (go-xkms#839-era code), but ListKeys never read it back, so
// every symmetric key -- however it was created -- enumerated as
// Exportable=false and ExportKeyMaterial was refused by policy no matter
// what the caller originally asked for.
func TestListKeys_SymmetricKeyRoundTripsExportableTrue(t *testing.T) {
	config := getTestVaultConfig(t)
	b, err := NewBackend(config)
	require.NoError(t, err)
	defer func() { _ = b.Close() }()
	ctx := context.Background()

	attrs := &types.KeyAttributes{
		CN:                 "listkeys-symmetric-exportable",
		KeyType:            backend.KEY_TYPE_SECRET,
		StoreType:          backend.STORE_VAULT,
		SymmetricAlgorithm: types.SymmetricAES256GCM,
		Exportable:         true,
		Sensitive:          false,
	}
	_, err = b.GenerateSymmetricKey(ctx, attrs)
	require.NoError(t, err)

	listed, err := b.ListKeys(ctx)
	require.NoError(t, err)

	ka := findListedByCN(t, listed, attrs.CN)
	assert.True(t, ka.Exportable, "ListKeys must report the caller's Exportable=true policy")
	assert.False(t, ka.Sensitive, "ListKeys must report the caller's Sensitive=false policy")

	material, err := b.ExportKeyMaterial(ctx, ka)
	require.NoError(t, err, "a key ListKeys reports as Exportable must actually export")
	assert.Len(t, material, 32, "Vault Transit aes256-gcm96 material is 32 bytes")
}

// TestListKeys_SymmetricKeyRoundTripsExportableFalse is the error case: a
// symmetric key created without Exportable must round-trip as
// Exportable=false and stay refused, proving the fix does not simply report
// every key exportable.
func TestListKeys_SymmetricKeyRoundTripsExportableFalse(t *testing.T) {
	config := getTestVaultConfig(t)
	b, err := NewBackend(config)
	require.NoError(t, err)
	defer func() { _ = b.Close() }()
	ctx := context.Background()

	attrs := &types.KeyAttributes{
		CN:                 "listkeys-symmetric-sealed",
		KeyType:            backend.KEY_TYPE_SECRET,
		StoreType:          backend.STORE_VAULT,
		SymmetricAlgorithm: types.SymmetricAES256GCM,
		Sensitive:          true,
	}
	_, err = b.GenerateSymmetricKey(ctx, attrs)
	require.NoError(t, err)

	listed, err := b.ListKeys(ctx)
	require.NoError(t, err)

	ka := findListedByCN(t, listed, attrs.CN)
	assert.False(t, ka.Exportable, "ListKeys must report the caller's default Exportable=false policy")
	assert.True(t, ka.Sensitive, "ListKeys must report the caller's Sensitive=true policy")

	_, err = b.ExportKeyMaterial(ctx, ka)
	assert.ErrorIs(t, err, backend.ErrKeyNotExportable,
		"a key ListKeys reports as sealed must stay refused")
}

// TestListKeys_AsymmetricKeyIsAlwaysReportedNonExportable proves H8 (see the
// Capabilities doc comment, vault.go): an asymmetric private key generated by
// this backend is never exportable in either form, regardless of what the
// caller's attrs.Exportable requested, because GenerateKey hardcodes
// exportable:false against Vault itself. ListKeys must report that
// truthfully rather than echoing the caller's request.
func TestListKeys_AsymmetricKeyIsAlwaysReportedNonExportable(t *testing.T) {
	config := getTestVaultConfig(t)
	b, err := NewBackend(config)
	require.NoError(t, err)
	defer func() { _ = b.Close() }()
	ctx := context.Background()

	// RSA, not ECDSA: transitDouble (transit_double_vault_test.go) only
	// generates a real keypair -- and so only answers the read-key request
	// GenerateKey makes for the public key -- for "rsa-*" Transit key types.
	attrs := &types.KeyAttributes{
		CN:            "listkeys-asymmetric-generated",
		KeyType:       backend.KEY_TYPE_SIGNING,
		StoreType:     backend.STORE_VAULT,
		KeyAlgorithm:  x509.RSA,
		RSAAttributes: &types.RSAAttributes{KeySize: 2048},
		Exportable:    true,
	}
	_, err = b.GenerateKey(ctx, attrs)
	require.NoError(t, err)

	listed, err := b.ListKeys(ctx)
	require.NoError(t, err)

	ka := findListedByCN(t, listed, attrs.CN)
	assert.False(t, ka.Exportable,
		"an asymmetric key is never exportable through this backend; ListKeys must not echo the caller's request")

	_, err = b.ExportKey(ctx, ka, backend.WrappingAlgorithmRSAES_OAEP_SHA_256)
	assert.Error(t, err, "ExportKey has no Vault-native equivalent and must refuse")
}
