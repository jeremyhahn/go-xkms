// newProvisionedBackend returns a Backend bound to a private SoftHSM2 token
// provisioned under t.TempDir(), already logged in and ready for key
// operations.
//
// The token store is created fresh for each test and SOFTHSM2_CONF is
// redirected at it, so tests never read or modify the host's SoftHSM state and
// never observe keys left behind by another test.
func newProvisionedBackend(t *testing.T, label string) *Backend {
	t.Helper()

	token := softhsmtest.Provision(t, label)

	config := testConfig(token.Library, token.Label)
	config.PIN = token.UserPIN
	config.SOPIN = token.SOPIN

	b, err := NewBackend(config)
	require.NoError(t, err, "pkcs11 backend must construct")

	require.NoError(t, b.Login(), "backend must log in to the provisioned token")
	t.Cleanup(func() { require.NoError(t, b.Close()) })

	return b
}

// openIntrospectionSession opens a read-only session on the backend's own
// PKCS#11 context so a test can read raw object attributes, and closes it when
// the test ends.
func openIntrospectionSession(t *testing.T, b *Backend) pkcs11.SessionHandle {
	t.Helper()

	require.NotNil(t, b.p11ctx, "a logged-in backend always holds a PKCS#11 context")

	slot, err := b.resolveSlot()
	require.NoError(t, err, "the provisioned token's slot must resolve")

	session, err := b.p11ctx.OpenSession(slot, pkcs11.CKF_SERIAL_SESSION)
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, b.p11ctx.CloseSession(session)) })

	return session
}

// findSingleObject locates exactly one PKCS#11 object matching the template and
// returns its handle.
func findSingleObject(t *testing.T, b *Backend, session pkcs11.SessionHandle, template []*pkcs11.Attribute) pkcs11.ObjectHandle {
	t.Helper()

	require.NoError(t, b.p11ctx.FindObjectsInit(session, template))
	defer func() { require.NoError(t, b.p11ctx.FindObjectsFinal(session)) }()

	handles, _, err := b.p11ctx.FindObjects(session, 1)
	require.NoError(t, err)
	require.Len(t, handles, 1, "the object generated by this test must be findable")

	return handles[0]
}
