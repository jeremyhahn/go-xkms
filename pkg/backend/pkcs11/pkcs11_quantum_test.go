// TestQuantumFamily_ParameterSet proves the exact parameter set is recovered
// from the identifier generateQuantumKey wrote, so a key found by CKA_ID
// reports the same algorithm it was created with.
func TestQuantumFamily_ParameterSet(t *testing.T) {
	for _, algorithm := range quantumTestAlgorithms {
		t.Run(string(algorithm), func(t *testing.T) {
			attrs := &types.KeyAttributes{
				CN:                "pq-parameter-set",
				StoreType:         types.StorePKCS11,
				QuantumAttributes: &types.QuantumAttributes{Algorithm: algorithm},
			}
			family, ok := quantumFamilyForAlgorithm(string(algorithm))
			require.True(t, ok)

			id := []byte(createQuantumKeyID(attrs))
			assert.Equal(t, string(algorithm), family.parameterSet(id))
		})
	}
}

// TestQuantumFamily_ParameterSet_Rejected proves an identifier this backend did
// not write degrades to the family name rather than being read as a parameter
// set the stack does not implement.
//
// The distinction matters because the parameter set is reported metadata while
// the mechanism that drives the token comes from CKA_KEY_TYPE: an identifier
// nobody recognises must cost precision, never correctness.
func TestQuantumFamily_ParameterSet_Rejected(t *testing.T) {
	tests := []struct {
		name   string
		family *quantumFamily
		id     string
		want   string
	}{
		{"no-separator", quantumFamilyMLDSA, "written-by-another-tool", "ML-DSA"},
		{"empty", quantumFamilyMLDSA, "", "ML-DSA"},
		{"unimplemented-parameter-set", quantumFamilyMLDSA, "key.ml-dsa-1024", "ML-DSA"},
		{"classical-suffix", quantumFamilyMLDSA, "key.rsa", "ML-DSA"},
		{"other-family-suffix", quantumFamilyMLDSA, "key.ml-kem-768", "ML-DSA"},
		{"other-family-suffix-kem", quantumFamilyMLKEM, "key.ml-dsa-65", "ML-KEM"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.want, tt.family.parameterSet([]byte(tt.id)))
		})
	}
}

// TestQuantumKey_GeneratedIdentifierIsUsable walks the whole chain a
// post-quantum key goes through after generation -- the identifier
// generateQuantumKey writes, the attributes ListKeys reports for it, the
// CKA_ID resolveKeyID computes from those attributes, and the wrapper
// findKeyPairByID builds from the key type behind that CKA_ID -- and requires
// the wrapper to come out driving the right mechanism under the right name.
//
// Everything except the token round trip is the production code path. The
// token leg is impossible here: TestSoftHSM2_RefusesPostQuantumObjects proves
// SoftHSM2 will not hold the object.
func TestQuantumKey_GeneratedIdentifierIsUsable(t *testing.T) {
	b := newProvisionedBackend(t, "pq-usable")

	for _, algorithm := range quantumTestAlgorithms {
		t.Run(string(algorithm), func(t *testing.T) {
			generated := &types.KeyAttributes{
				CN:                "pq-usable-key",
				StoreType:         types.StorePKCS11,
				QuantumAttributes: &types.QuantumAttributes{Algorithm: algorithm},
			}
			family, ok := quantumFamilyForAlgorithm(string(algorithm))
			require.True(t, ok)

			// Generation writes this to both CKA_ID and CKA_LABEL.
			id := []byte(createQuantumKeyID(generated))

			// Enumeration decodes the label back into attributes.
			listed := &types.KeyAttributes{StoreType: types.StorePKCS11}
			decodeKeyType(listed, family.keyType, string(id))
			require.NotNil(t, listed.QuantumAttributes)
			require.Equal(t, algorithm, listed.QuantumAttributes.Algorithm)

			// Resolution turns those attributes back into the CKA_ID.
			resolved, err := b.resolveKeyID(listed)
			require.NoError(t, err)
			require.Equal(t, id, resolved)

			// Lookup dispatches on the CKA_KEY_TYPE read off the object.
			factory, ok := signerFactories[family.keyType]
			require.True(t, ok, "a generated %s key must be dispatchable", algorithm)

			signer, err := factory(b.Pool(), pkcs11.ObjectHandle(11), pkcs11.ObjectHandle(12), resolved)
			require.NoError(t, err)
			require.NotNil(t, signer)

			quantum, ok := signer.(*pkcs11MLDSASigner)
			require.True(t, ok, "a post-quantum key must yield the post-quantum wrapper, not %T", signer)
			assert.Same(t, family, quantum.family)
			assert.Equal(t, string(algorithm), quantum.algorithm,
				"the wrapper must report the parameter set the key was created with")
			assert.Equal(t, string(id), quantum.label)
			assert.Equal(t, pkcs11.ObjectHandle(12), quantum.privateHandle)

			public, ok := signer.Public().(*pkcs11QuantumPublicKey)
			require.True(t, ok, "a post-quantum key must expose a post-quantum public key")
			assert.Equal(t, pkcs11.ObjectHandle(11), public.Handle())
			assert.Equal(t, string(algorithm), public.Algorithm())
			assert.Same(t, family, public.family)
			assert.Same(t, b.Pool(), public.pool,
				"verification runs on the token, so the public key must carry the session pool")
		})
	}
}

// TestSoftHSM2_RefusesPostQuantumObjects records, as an assertion rather than
// as an unstated gap, why no test in this package signs with a real ML-DSA key.
//
// SoftHSM2 rejects a CKK_ML_DSA or CKK_ML_KEM object outright and advertises
// neither generation mechanism, so a post-quantum key cannot be put on the CI
// token by any route. Should a future SoftHSM2 release accept them, this test
// fails and the end-to-end coverage becomes possible.
func TestSoftHSM2_RefusesPostQuantumObjects(t *testing.T) {
	b := newProvisionedBackend(t, "pq-token-refusal")

	require.False(t, b.supportsMLDSA, "SoftHSM2 advertises no ML-DSA generation mechanism")
	require.False(t, b.supportsMLKEM, "SoftHSM2 advertises no ML-KEM generation mechanism")

	for _, family := range quantumFamilies {
		t.Run(family.name, func(t *testing.T) {
			require.NoError(t, b.Pool().WithSession(func(session pkcs11.SessionHandle) error {
				public, private := quantumKeyTemplates(family.keyType, []byte("refused.pq"))

				handle, err := b.p11ctx.CreateObject(session, public)
				assert.ErrorIs(t, err, pkcs11.Error(pkcs11.CKR_ATTRIBUTE_VALUE_INVALID),
					"SoftHSM2 must reject a %s public key object", family.name)
				assert.Zero(t, handle)

				handle, err = b.p11ctx.CreateObject(session, private)
				assert.ErrorIs(t, err, pkcs11.Error(pkcs11.CKR_ATTRIBUTE_VALUE_INVALID),
					"SoftHSM2 must reject a %s private key object", family.name)
				assert.Zero(t, handle)

				_, _, err = b.p11ctx.GenerateKeyPair(session,
					[]*pkcs11.Mechanism{pkcs11.NewMechanism(family.keyPairGen, nil)},
					public, private)
				assert.ErrorIs(t, err, pkcs11.Error(pkcs11.CKR_MECHANISM_INVALID),
					"SoftHSM2 must reject %s key pair generation", family.name)
				return nil
			}))
		})
	}
}

// TestBackend_Signer_QuantumKeyReachesTheToken proves Signer routes a
// post-quantum key to a token lookup on the CKA_ID the key would live under,
// instead of refusing the algorithm before it ever gets there.
//
// The token holds no such key -- it cannot -- so the expected answer is
// ErrKeyNotFound. That it is ErrKeyNotFound and not ErrUnsupportedKeyAlgorithm
// is the whole point: the second was the answer before ML-DSA keys were
// dispatchable, and it is indistinguishable from "this backend cannot do
// post-quantum at all".
func TestBackend_Signer_QuantumKeyReachesTheToken(t *testing.T) {
	b := newProvisionedBackend(t, "pq-signer-lookup")

	for _, algorithm := range quantumTestAlgorithms {
		t.Run(string(algorithm), func(t *testing.T) {
			attrs := &types.KeyAttributes{
				CN:                "absent-pq-key",
				StoreType:         types.StorePKCS11,
				QuantumAttributes: &types.QuantumAttributes{Algorithm: algorithm},
			}

			signer, err := b.Signer(context.Background(), attrs)
			require.ErrorIs(t, err, backend.ErrKeyNotFound)
			assert.Contains(t, err.Error(), "absent-pq-key")
			assert.Nil(t, signer)

			err = b.Verify(attrs, []byte("message"), []byte("signature"))
			require.ErrorIs(t, err, backend.ErrKeyNotFound)
		})
	}
}

// TestPkcs11MLDSASigner_Sign_Refused proves the post-quantum wrapper refuses
// the operations its family does not define, and does so before touching the
// token.
//
// The ML-KEM case is the one that matters: FIPS 203 defines encapsulation, not
// signing, so a caller that asks an ML-KEM key to sign is told exactly that
// rather than being handed CKR_MECHANISM_INVALID from the device.
func TestPkcs11MLDSASigner_Sign_Refused(t *testing.T) {
	b := newProvisionedBackend(t, "pq-sign-refused")

	t.Run("ml-kem-cannot-sign", func(t *testing.T) {
		signer := &pkcs11MLDSASigner{
			pool:      b.Pool(),
			algorithm: "ML-KEM-768",
			family:    quantumFamilyMLKEM,
		}

		signature, err := signer.Sign(rand.Reader, []byte("message"), crypto.Hash(0))
		require.ErrorIs(t, err, ErrUnsupportedKeyAlgorithm)
		assert.Contains(t, err.Error(), "ML-KEM-768 is a key encapsulation mechanism and cannot sign")
		assert.Nil(t, signature)
	})

	t.Run("no-family", func(t *testing.T) {
		signer := &pkcs11MLDSASigner{pool: b.Pool(), algorithm: "ML-DSA-65"}

		signature, err := signer.Sign(rand.Reader, []byte("message"), crypto.Hash(0))
		require.ErrorIs(t, err, ErrUnsupportedKeyAlgorithm)
		assert.Contains(t, err.Error(), "no algorithm family")
		assert.Nil(t, signature)
	})

	t.Run("no-session-pool", func(t *testing.T) {
		signer := &pkcs11MLDSASigner{algorithm: "ML-DSA-65", family: quantumFamilyMLDSA}

		signature, err := signer.Sign(rand.Reader, []byte("message"), crypto.Hash(0))
		require.Error(t, err)
		assert.Contains(t, err.Error(), "session pool not initialized")
		assert.Nil(t, signature)
	})
}

// TestVerifyQuantum_ReachesTheToken proves a post-quantum verification is
// carried out by the token with the mechanism belonging to the key's family.
//
// SoftHSM2 implements no such mechanism, so what the token returns is
// CKR_MECHANISM_INVALID from C_VerifyInit. The value of the assertion is that
// the failure comes from the device, under the ML-DSA mechanism and the key's
// own parameter set: the call reached the token, which is as far as this token
// permits.
func TestVerifyQuantum_ReachesTheToken(t *testing.T) {
	b := newProvisionedBackend(t, "pq-verify-token")

	// A real public key object on this token, so the refusal is about the
	// mechanism rather than about an object handle that never existed.
	attrs := ecdsaKeyAttrs("pq-verify-handle", elliptic.P256())
	_, err := b.GenerateKey(context.Background(), attrs)
	require.NoError(t, err)

	id, err := b.resolveKeyID(attrs)
	require.NoError(t, err)

	var handle pkcs11.ObjectHandle
	require.NoError(t, b.Pool().WithSession(func(session pkcs11.SessionHandle) error {
		handle = findSingleObject(t, b, session, []*pkcs11.Attribute{
			pkcs11.NewAttribute(pkcs11.CKA_CLASS, pkcs11.CKO_PUBLIC_KEY),
			pkcs11.NewAttribute(pkcs11.CKA_ID, id),
		})
		return nil
	}))

	public := &pkcs11QuantumPublicKey{
		pool:      b.Pool(),
		handle:    handle,
		algorithm: "ML-DSA-65",
		family:    quantumFamilyMLDSA,
	}

	err = verifyQuantum(public, []byte("message"), []byte("signature"))
	require.Error(t, err)
	assert.Contains(t, err.Error(), "pkcs11: ML-DSA-65 VerifyInit")
	assert.ErrorIs(t, err, pkcs11.Error(pkcs11.CKR_MECHANISM_INVALID),
		"the token was driven with CKM_ML_DSA and answered that it does not implement it")
	assert.NotContains(t, err.Error(), "signature verification failed",
		"a mechanism the token does not implement is not a bad signature")
}

// TestVerifyQuantum_Refused proves verification is refused for a key that
// produces no signature, and for a wrapper that carries nothing to verify
// with, rather than reporting a bad signature for either.
func TestVerifyQuantum_Refused(t *testing.T) {
	tests := []struct {
		name   string
		public *pkcs11QuantumPublicKey
		detail string
	}{
		{
			name:   "ml-kem-has-no-signature",
			public: &pkcs11QuantumPublicKey{algorithm: "ML-KEM-1024", family: quantumFamilyMLKEM},
			detail: "ML-KEM-1024 is a key encapsulation mechanism and produces no signature to verify",
		},
		{
			name:   "no-family",
			public: &pkcs11QuantumPublicKey{algorithm: "ML-DSA-65"},
			detail: "no algorithm family",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := verifyQuantum(tt.public, []byte("message"), []byte("signature"))
			require.ErrorIs(t, err, backend.ErrInvalidKeyType)
			assert.Contains(t, err.Error(), tt.detail)
		})
	}

	t.Run("no-session-pool", func(t *testing.T) {
		public := &pkcs11QuantumPublicKey{algorithm: "ML-DSA-65", family: quantumFamilyMLDSA}

		err := verifyQuantum(public, []byte("message"), []byte("signature"))
		require.Error(t, err)
		assert.Contains(t, err.Error(), "session pool not initialized")
	})
}

// TestVerifyPublicKey_RoutesPostQuantumKeys proves Verify sends a post-quantum
// public key to the token instead of falling through to "unsupported key type
// for verification".
//
// This is the routing Verify performs on whatever the token handed back, tested
// where it can be reached: SoftHSM2 will not hold an ML-DSA object, so Verify
// itself cannot be walked all the way to this branch on the CI token.
func TestVerifyPublicKey_RoutesPostQuantumKeys(t *testing.T) {
	attrs := &types.KeyAttributes{
		CN:                "pq-verify-routing",
		StoreType:         types.StorePKCS11,
		QuantumAttributes: &types.QuantumAttributes{Algorithm: types.QuantumAlgorithmMLDSA65},
	}

	t.Run("ml-dsa-goes-to-the-token", func(t *testing.T) {
		// No session pool, so verifyQuantum is identifiable by the point at
		// which it stops: it got as far as needing the token.
		public := &pkcs11QuantumPublicKey{algorithm: "ML-DSA-65", family: quantumFamilyMLDSA}

		err := verifyPublicKey(public, attrs, []byte("message"), []byte("signature"))
		require.Error(t, err)
		assert.Contains(t, err.Error(), "session pool not initialized")
		assert.NotErrorIs(t, err, backend.ErrInvalidKeyType,
			"a post-quantum key is verifiable, so it must not be reported as an unsupported key type")
	})

	t.Run("ml-kem-is-refused-as-a-key-type", func(t *testing.T) {
		public := &pkcs11QuantumPublicKey{algorithm: "ML-KEM-768", family: quantumFamilyMLKEM}

		err := verifyPublicKey(public, attrs, []byte("message"), []byte("signature"))
		require.ErrorIs(t, err, backend.ErrInvalidKeyType)
		assert.Contains(t, err.Error(), "produces no signature to verify")
	})

	t.Run("unmodelled-key-type", func(t *testing.T) {
		err := verifyPublicKey("not a public key", attrs, []byte("message"), []byte("signature"))
		require.ErrorIs(t, err, backend.ErrInvalidKeyType)
		assert.Contains(t, err.Error(), "unsupported key type for verification")
	})
}

// TestIsSignatureRejection proves a signature the token examined and rejected
// is told apart from a failure that means the token never got that far.
//
// Collapsing the two would report a device fault or a lost session as a forged
// signature, which is the more dangerous direction of the two: it invites a
// caller to retry against a broken token instead of surfacing the outage.
func TestIsSignatureRejection(t *testing.T) {
	t.Run("rejections", func(t *testing.T) {
		for _, code := range []uint{pkcs11.CKR_SIGNATURE_INVALID, pkcs11.CKR_SIGNATURE_LEN_RANGE} {
			assert.True(t, isSignatureRejection(pkcs11.Error(code)), "0x%02x is a rejected signature", code)
		}
	})

	t.Run("wrapped-rejection", func(t *testing.T) {
		wrapped := &errs.Wrapped{Msg: "pkcs11: ML-DSA-65 Verify", Err: pkcs11.Error(pkcs11.CKR_SIGNATURE_INVALID)}
		assert.True(t, isSignatureRejection(wrapped), "a rejection keeps its meaning through a wrapper")
	})

	t.Run("not-rejections", func(t *testing.T) {
		for _, err := range []error{
			pkcs11.Error(pkcs11.CKR_DEVICE_ERROR),
			pkcs11.Error(pkcs11.CKR_SESSION_HANDLE_INVALID),
			pkcs11.Error(pkcs11.CKR_MECHANISM_INVALID),
			pkcs11.Error(pkcs11.CKR_OK),
			ErrSessionPoolClosed,
			&errs.Message{Msg: "not a token error at all"},
		} {
			assert.False(t, isSignatureRejection(err), "%v does not mean the signature was examined and rejected", err)
		}
	})

	t.Run("nil", func(t *testing.T) {
		assert.False(t, isSignatureRejection(nil))
	})
}

// TestBackend_Verify_ClassicalKeysStillDispatch proves adding the post-quantum
// branch left the classical verification paths intact, checked against a key
// this token can actually hold.
func TestBackend_Verify_ClassicalKeysStillDispatch(t *testing.T) {
	b := newProvisionedBackend(t, "pq-verify-classical")

	attrs := ecdsaKeyAttrs("classical-verify", elliptic.P256())

	_, err := b.GenerateKey(context.Background(), attrs)
	require.NoError(t, err)

	digest := sha256.Sum256([]byte("classical message"))
	signature, err := b.Sign(attrs, digest[:], crypto.SHA256)
	require.NoError(t, err)

	require.NoError(t, b.Verify(attrs, digest[:], signature))

	forged := make([]byte, len(signature))
	copy(forged, signature)
	forged[len(forged)-1] ^= 0xff
	assert.Error(t, b.Verify(attrs, digest[:], forged),
		"a tampered signature must not verify")
}
