// Post-quantum key lifecycle tests.
//
// SoftHSM2 refuses to hold a post-quantum object at all -- see
// TestSoftHSM2_RefusesPostQuantumObjects, which asserts that refusal rather
// than leaving it unstated -- so the token leg of an ML-DSA sign or verify
// cannot be exercised here. What is exercised instead is the dispatch these
// operations run through: the tests below call the exact functions the
// production path calls (signerFactories, newQuantumSigner, verifyQuantum) and
// assert that a key generated by this backend is addressable, that the
// mechanism the token would be driven with is the one belonging to the key
// type, and that operations a post-quantum family does not define are refused.

package pkcs11

