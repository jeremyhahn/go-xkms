// shippedDaemonConfigs are the configs in configs/ that are handed to xkmsd.
//
// xkms-client.yaml is deliberately absent: it configures a client, enables no
// server protocol, and is never passed to the daemon, so Validate rejects it by
// design.
var shippedDaemonConfigs = []string{
	"xkmsd.yaml",
	"xkmsd-dev.yaml",
	"xkmsd-local.yaml",
	"xkmsd-integration.yaml",
}

// TestShippedDaemonConfigsAreCompliant pins the property that every config we
// ship can actually start a daemon.
//
// cmd/xkmsd refuses to serve a configuration with any compliance gap and has no
// override flag, so a shipped config that reports a gap is not merely insecure
// — it is inert, and the failure surfaces as a container that will not come up
// rather than as anything pointing at the config. That is exactly how
// configs/xkmsd-integration.yaml silently disabled the pkcs11-backend and gRPC
// integration lanes: the compose service exited at startup and the suite fell
// through to a software-only fallback daemon, which looked like a backend
// defect. This test is the guard for that, and it fails with the offending file
// and the exact gaps rather than leaving it to be rediscovered downstream.
func TestShippedDaemonConfigsAreCompliant(t *testing.T) {
	for _, name := range shippedDaemonConfigs {
		t.Run(name, func(t *testing.T) {
			path := filepath.Join("..", "..", "configs", name)
			if _, err := os.Stat(path); err != nil {
				t.Fatalf("shipped config is missing: %v", err)
			}
			cfg, err := Load(path)
			if err != nil {
				t.Fatalf("Load(%s) failed, so xkmsd could not start with it: %v", name, err)
			}
			gaps := cfg.ComplianceGaps()
			for _, gap := range gaps {
				t.Errorf("compliance gap: %s", gap)
			}
			if len(gaps) > 0 {
				t.Fatalf("%s reports %d compliance gap(s); cmd/xkmsd refuses to start with it "+
					"and offers no override", name, len(gaps))
			}
		})
	}
}

// TestConformanceConfigsAllowWeakHashes pins the weak-hash opt-in on the two
// configs whose suites depend on it.
//
// The PKCS#11 module advertises the OASIS SHA-1 mechanisms (CKM_SHA1_RSA_PKCS,
// CKM_ECDSA_SHA1), and the daemon performs the digest the module names on the
// wire. Since xkms refuses the collision-broken digests by default, a
// conformance run against a daemon that has not opted in fails on every one of
// those mechanisms — and it fails as a mechanism error, which reads like a
// module defect rather than a configuration choice.
//
// Asserting it here keeps the two files in step: scripts/start-test-xkmsd.sh
// generates the fallback daemon's config with this set, and
// configs/xkmsd-integration.yaml serves the same socket from compose. They
// drifted once already, with only the script carrying the opt-in.
func TestConformanceConfigsAllowWeakHashes(t *testing.T) {
	path := filepath.Join("..", "..", "configs", "xkmsd-integration.yaml")
	cfg, err := Load(path)
	if err != nil {
		t.Fatalf("Load: %v", err)
	}
	if !cfg.Crypto.AllowWeakHashes {
		t.Error("crypto.allow_weak_hashes is not set, so the SHA-1 mechanisms the " +
			"PKCS#11 conformance suite exercises will be refused by the daemon")
	}
}

// TestIntegrationConfigsAllowLegacyKeyWrap pins the legacy key-wrap opt-in on
// both test daemon configs.
//
// The PKCS#11 OpenSSL suites decrypt RSA PKCS#1 v1.5 ciphertext through the
// module (CKM_RSA_PKCS, PKCS#11 v3.2 §6.1.6), which libp11 and the pkcs11
// provider use for "pkeyutl -decrypt". The daemon refuses that padding on
// Decrypt unless crypto.allow_legacy_key_wrap is set, and the module reports
// the refusal as CKR_ARGUMENTS_BAD, which reads like a module defect rather
// than a configuration choice.
//
// The fallback daemon's config is generated by scripts/start-test-xkmsd.sh,
// so the script is checked for the same line the compose config carries.
func TestIntegrationConfigsAllowLegacyKeyWrap(t *testing.T) {
	path := filepath.Join("..", "..", "configs", "xkmsd-integration.yaml")
	cfg, err := Load(path)
	if err != nil {
		t.Fatalf("Load: %v", err)
	}
	if !cfg.Crypto.AllowLegacyKeyWrap {
		t.Error("configs/xkmsd-integration.yaml: crypto.allow_legacy_key_wrap is not set, " +
			"so the RSA PKCS#1 v1.5 decrypt the OpenSSL suites exercise will be refused")
	}

	script, err := os.ReadFile(filepath.Join("..", "..", "scripts", "start-test-xkmsd.sh"))
	if err != nil {
		t.Fatalf("ReadFile: %v", err)
	}
	if !strings.Contains(string(script), "\n  allow_legacy_key_wrap: true\n") {
		t.Error("scripts/start-test-xkmsd.sh: the generated config does not set " +
			"crypto.allow_legacy_key_wrap, so it has drifted from configs/xkmsd-integration.yaml")
	}
}

// TestIntegrationConfigSealedWindow pins the sealed-window posture of the
// compose xkms-server configs: the devcontainer's and the API suite's
// (make integration-test-cli).
//
// Their passphrase barrier boots sealed, and the sealed-window listener binds
// server.host, which must stay a wildcard so the suites can dial the server
// over the compose network once it is unsealed. pkg/server refuses that bind
// unless barrier.sealed_window_allow_remote is set, and the daemon exits at
// startup: the compose stack then fails with nothing pointing at the config.
func TestIntegrationConfigSealedWindow(t *testing.T) {
	paths := []string{
		filepath.Join("..", "..", "configs", "xkmsd-integration.yaml"),
		filepath.Join("..", "..", "test", "integration", "api", "config.test.yaml"),
	}
	for _, path := range paths {
		t.Run(filepath.Base(path), func(t *testing.T) {
			cfg, err := Load(path)
			if err != nil {
				t.Fatalf("Load: %v", err)
			}
			if !cfg.Barrier.Enabled || cfg.Barrier.SealStrategy() != "passphrase" {
				t.Fatalf("barrier = enabled %v strategy %q; the suites drive a passphrase barrier",
					cfg.Barrier.Enabled, cfg.Barrier.SealStrategy())
			}
			if cfg.Server.Host != "0.0.0.0" {
				t.Errorf("server.host = %q; the suites dial xkms-server over the compose network", cfg.Server.Host)
			}
			if !cfg.Barrier.SealedWindowAllowRemote {
				t.Error("barrier.sealed_window_allow_remote is not set, so the sealed window refuses " +
					"to bind server.host and the compose xkms-server exits at startup")
			}
		})
	}
}

// TestProductionConfigsKeepSealedWindowLocal pins the opposite default on the
// configs a deployment starts from: none of them accepts a remotely reachable
// sealed window.
func TestProductionConfigsKeepSealedWindowLocal(t *testing.T) {
	for _, name := range shippedDaemonConfigs {
		if name == "xkmsd-integration.yaml" {
			continue
		}
		t.Run(name, func(t *testing.T) {
			cfg, err := Load(filepath.Join("..", "..", "configs", name))
			if err != nil {
				t.Fatalf("Load: %v", err)
			}
			if cfg.Barrier.SealedWindowAllowRemote {
				t.Errorf("%s sets barrier.sealed_window_allow_remote", name)
			}
		})
	}
}

// TestWebAuthnBrowserConfigValidates loads the WebAuthn browser suite's xkmsd
// config through the loader xkmsd uses: Playwright's webServer cannot start
// xkmsd when it fails validation (main run 73740: TLS disabled on a serving
// node, config.go Validate).
func TestWebAuthnBrowserConfigValidates(t *testing.T) {
	path := filepath.Join("..", "..", "test", "integration", "webauthn-browser", "config.yaml")
	cfg, err := Load(path)
	if err != nil {
		t.Fatalf("Load(%s) failed, so xkmsd could not start with it: %v", path, err)
	}
	if err := cfg.Validate(); err != nil {
		t.Fatalf("Validate() = %v, want nil", err)
	}
	if !cfg.TLS.Enabled {
		t.Fatal("tls.enabled = false; the REST transport is TLS-only")
	}
	if gaps := cfg.ComplianceGaps(); len(gaps) > 0 {
		t.Fatalf("ComplianceGaps() = %q, want none; xkmsd refuses to start with an insecure configuration", gaps)
	}
}
