// NIST CAVP KDF108 test vectors for SP 800-108 key-based key derivation.
//
// Provenance: these are official Cryptographic Algorithm Validation Program
// response files published by NIST, not hand-computed values:
//
//	Counter mode:    KBKDF800-108/CounterMode.zip            -> KDFCTR_gen.rsp
//	Feedback mode:   KBKDF800-108/FeedbackModeNOzeroiv.zip   -> KDFFeedback_gen.rsp
//	Double-pipeline: KBKDF800-108/PipelineModewithCounter.zip -> KDFDblPipeline_gen.rsp
//
// published under
// https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/documents/
//
// The selection below covers the HMAC-SHA256, HMAC-SHA384, and HMAC-SHA512
// PRFs across every counter width the specification permits (8, 16, 24, and
// 32 bits) and both counter placements this implementation supports. The
// CMAC PRF groups in the same files are not covered: this package derives
// with HMAC only.
//
// CAVP counter locations map onto KDFParams.CounterLocation as follows. The
// chaining value (K(i-1) in feedback mode, A(i) in double-pipeline mode)
// always precedes the fixed input data, so CAVP's "after iteration variable"
// is this package's "before" (before the fixed input data):
//
//	BEFORE_FIXED -> "before"   AFTER_FIXED -> "after"   AFTER_ITER -> "before"
//
// CAVP supplies the assembled fixed input data as an opaque blob, which is
// what KDFParams.FixedInput accepts.

// cavpVector is one CAVP response record. Byte fields are hex encoded exactly
// as they appear in the .rsp file.
type cavpVector struct {
	name       string
	hash       crypto.Hash
	location   string
	counterLen int
	keyLen     int
	ki         string
	fixedInput string
	iv         string
	ko         string
}

