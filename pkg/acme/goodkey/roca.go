package goodkey

import "math/big"

// rocaGenerator is the generator of the Infineon RSALib prime construction
// p = k*M + (65537^a mod M), M a primorial (Nemec et al., "The Return of
// Coppersmith's Attack", ACM CCS 2017, §2.3).
const rocaGenerator = 65537

// rocaPrimeBound bounds the primes of the fingerprint: the first 38 primes,
// 3 to 167, all of which divide M for every RSALib key size (§2.3, Table 1).
const rocaPrimeBound = 168

// rocaPrime is one prime p of the fingerprint and the residues of the
// subgroup of (Z/pZ)* that 65537 generates.
type rocaPrime struct {
	prime    *big.Int
	residues map[int64]struct{}
}

// rocaFingerprints returns, for each fingerprint prime, the subgroup
// generated by 65537 mod p.
func rocaFingerprints() []rocaPrime {
	var fingerprints []rocaPrime
	for _, p := range primesBelow(rocaPrimeBound) {
		if p == 2 {
			continue
		}
		residues := make(map[int64]struct{})
		g := int64(rocaGenerator % p)
		for r := int64(1); ; r = r * g % int64(p) {
			if _, seen := residues[r]; seen {
				break
			}
			residues[r] = struct{}{}
		}
		fingerprints = append(fingerprints, rocaPrime{prime: big.NewInt(int64(p)), residues: residues})
	}
	return fingerprints
}

// hasROCAFingerprint reports whether N mod p lies in the subgroup generated
// by 65537 for every fingerprint prime p. The product of two RSALib primes
// always does; a random modulus does with negligible probability.
func (v *Validator) hasROCAFingerprint(n *big.Int) bool {
	residue := new(big.Int)
	for _, fp := range v.rocaPrimes {
		residue.Mod(n, fp.prime)
		if _, ok := fp.residues[residue.Int64()]; !ok {
			return false
		}
	}
	return true
}
