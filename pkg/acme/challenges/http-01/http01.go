// Verify performs http-01 challenge verification as defined in RFC 8555.
//
// The function sends an HTTP GET request to http://{domain}:{port}/.well-known/acme-challenge/{token}
// and verifies that the response body matches the expected key authorization.
//
// Parameters:
//   - resolver: DNS resolver for domain name resolution
//   - ca: Certificate Authority instance (reserved for future use)
//   - domain: Domain name to verify (e.g., "example.com")
//   - port: HTTP port number to connect to (typically "80" or custom port)
//   - challengeToken: Unique token generated by ACME server
//   - expectedKeyAuth: Expected key authorization value (token.thumbprint)
//
// Returns:
//   - nil if challenge verification succeeds
//   - error if verification fails (network error, status code mismatch, key authorization mismatch)
//
// RFC 8555 Section 8.3: The client provisions the key authorization as a resource
// on the HTTP server for the domain in the challenge.
func Verify(
	resolver *net.Resolver,
	ca CertificateAuthority,
	domain, port, challengeToken, expectedKeyAuth string) error {

	url := fmt.Sprintf("http://%s:%s%s%s", domain, port, wellKnownChallengePath, challengeToken)

	client := &http.Client{
		Timeout: 10 * time.Second,
		Transport: &http.Transport{
			DialContext: (&net.Dialer{
				Timeout:   5 * time.Second,
				KeepAlive: 5 * time.Second,
				Resolver:  resolver,
			}).DialContext,
			TLSHandshakeTimeout:   5 * time.Second,
			ResponseHeaderTimeout: 5 * time.Second,
			ExpectContinueTimeout: 1 * time.Second,
			// HTTP-01 is plain HTTP per RFC 8555 - no TLS config needed
			// since we don't follow redirects
		},
		// Don't follow redirects per RFC 8555
		CheckRedirect: func(req *http.Request, via []*http.Request) error {
			return http.ErrUseLastResponse
		},
	}

	resp, err := client.Get(url)
	if err != nil {
		return err
	}
	defer func() { _ = resp.Body.Close() }()

	if resp.StatusCode != http.StatusOK {
		return ErrUnexpectedHTTPStatus{Domain: domain, Status: resp.Status}
	}

	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return err
	}

	if strings.TrimSpace(string(body)) != expectedKeyAuth {
		return ErrKeyAuthorizationMismatch{Domain: domain}
	}

	return nil
}

// Setup initializes an HTTP server to respond to http-01 challenges.
//
// The server listens on the specified port and serves the key authorization
// at the well-known challenge path. This function is typically called by
// ACME clients to prepare for challenge validation.
//
// Parameters:
//   - port: Port number to listen on (e.g., "80", "8080")
//   - keyAuth: Key authorization to serve in response to challenge requests
//
// The server runs in a background goroutine and can be stopped using Shutdown().
func Setup(port, keyAuth string) {

	mux := http.NewServeMux()
	mux.HandleFunc(wellKnownChallengePath, challengeHandlerHTTPx(keyAuth))

	slog.Info("Setting up http-01 challenge", slog.String("port", port))

	serverMu.Lock()
	// Reset shutdownOnce for new server instance
	shutdownOnce = sync.Once{}
	server = &http.Server{
		Addr:         port,
		Handler:      mux,
		ReadTimeout:  5 * time.Second,
		WriteTimeout: 10 * time.Second,
		IdleTimeout:  120 * time.Second,
	}
	currentServer := server
	serverMu.Unlock()

	go func() {
		listener, err := net.Listen("tcp", fmt.Sprintf(":%s", port))
		if err != nil {
			fatalHandler("Failed to listen on %s: %v", port, err)
			return
		}
		if err := currentServer.Serve(listener); err != nil && err != http.ErrServerClosed {
			fatalHandler("HTTP server error: %v", err)
			return
		}
	}()
}

// Shutdown gracefully stops the HTTP challenge server.
//
// The function initiates a graceful shutdown with a timeout, allowing
// in-flight requests to complete. This function is safe to call multiple
// times; subsequent calls are no-ops.
func Shutdown() {
	slog.Info("Shutting down HTTP challenge server")
	serverMu.Lock()
	currentServer := server
	once := &shutdownOnce
	serverMu.Unlock()

	once.Do(func() {
		if currentServer == nil {
			return
		}
		ctx, cancel := context.WithTimeout(context.Background(), serverShutdownTimeout)
		defer cancel()
		if err := currentServer.Shutdown(ctx); err != nil {
			fatalHandler("Server shutdown failed: %v", err)
		}
	})
}

// challengeHandlerHTTPx returns an HTTP handler function that serves the key authorization
// for http-01 challenges using the port number specified in the ACME configuration.
//
// The handler responds with Content-Type: text/plain and the key authorization value.
func challengeHandlerHTTPx(keyAuth string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {

		// Serve the key authorization
		w.Header().Set("Content-Type", "text/plain")
		w.WriteHeader(http.StatusOK)
		_, err := w.Write([]byte(keyAuth))
		if err != nil {
			slog.Error("Failed to write response for key authorization",
				slog.String("key-authorization", keyAuth),
				slog.String("error", err.Error()))
			return
		}

		slog.Debug("Served key authorization",
			slog.String("key-authorization", keyAuth),
			slog.String("remote-addr", r.RemoteAddr),
			slog.String("request-uri", r.RequestURI),
			slog.String("http-method", r.Method),
			slog.String("host-header", r.Header.Get("HOST")),
		)
	}
}
