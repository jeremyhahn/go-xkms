// Package nonce implements an encrypted nonce service for ACME protocol.
//
// Nonces in ACME are used to prevent replay attacks. Each request to the
// ACME server must include a unique nonce that was issued by that server.
// The server tracks which nonces have been used to prevent reuse.
//
// # Encryption
//
// Nonces are generated by encrypting a monotonically increasing counter
// using AES-GCM. This provides:
//
//   - Unpredictability: Clients cannot guess valid nonces
//   - Compactness: Encrypted counter is smaller than random nonces
//   - Verification: Invalid nonces can be detected during decryption
//
// # Cross-Off List
//
// To track used nonces efficiently, the service maintains:
//
//   - A counter of the latest issued nonce
//   - A counter of the earliest valid nonce
//   - A map of used nonces in the valid range
//   - A min-heap for efficient retirement of oldest nonces
//
// When maxUsed is exceeded, the oldest used nonce is retired and the
// earliest counter is advanced.
//
// # Prefix Support
//
// For distributed deployments, each nonce service can have a unique prefix.
// This allows:
//
//   - Multiple servers to issue nonces independently
//   - Nonces to be routed to the correct server for validation
//   - Deterministic prefix derivation from server address
//
// # Example Usage
//
//	// Create a nonce service with a prefix
//	prefix := nonce.DerivePrefix("server1:8443", secretKey)
//	svc, err := nonce.NewService(
//	    nonce.WithPrefix(prefix),
//	    nonce.WithMaxUsed(100000),
//	)
//
//	// Generate a nonce for a client
//	n, err := svc.Generate()
//
//	// Redeem a nonce from a client request
//	err = svc.Redeem(clientNonce)
//	if err != nil {
//	    // Invalid or already used nonce
//	}
//
// # Multi-Service Support
//
// For load-balanced deployments, MultiService can route nonces to the
// appropriate service based on prefix:
//
//	local, _ := nonce.NewService(nonce.WithPrefix("AAAAAAAA"))
//	remote, _ := nonce.NewService(nonce.WithPrefix("BBBBBBBB"))
//
//	multi := nonce.NewMultiService(local)
//	multi.Register(remote)
//
//	// Nonces are automatically routed based on prefix
//	err := multi.Redeem(someNonce)
