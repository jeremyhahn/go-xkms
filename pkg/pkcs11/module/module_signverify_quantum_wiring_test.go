// TestSignMessageMLDSAReachesTheInProcessSigner covers the v3.0 message-based
// spelling of the same request.
//
// C_MessageSignInit and C_SignMessage delegate to C_SignInit and C_Sign, so
// they were broken by the same defect and are fixed by the same hooks. The test
// exists because that delegation is an implementation choice: if either grew
// its own body, ML-DSA would silently go back to the transport there while the
// single-part tests above stayed green.
func TestSignMessageMLDSAReachesTheInProcessSigner(t *testing.T) {
	message := []byte("C_SignMessage must reach the in-process ML-DSA signer")

	m, client := transportWatchingModule(t)
	defer m.Finalize()
	session := loginAsNormalUser(t, m)

	pub, priv := generatePQCKeyPair(t, m, session, CKM_ML_DSA_KEY_PAIR_GEN, "mldsa-message",
		parameterSetAttribute(CKP_ML_DSA_65))
	publicKey := objectAttribute(t, m, pub, CKA_VALUE)

	require.Equal(t, CKR_OK, m.MessageSignInit(session, &Mechanism{Type: CKM_ML_DSA}, priv))
	signature, rv := m.SignMessage(session, message)
	require.Equal(t, CKR_OK, rv)

	require.Len(t, signature, mldsa65.SignatureSize)
	assert.True(t, circlVerifyMLDSA65(publicKey, message, signature),
		"cloudflare/circl must accept the signature C_SignMessage returned")
	assert.False(t, client.signCalled, "C_SignMessage must not reach the transport for such a key")

	require.Equal(t, CKR_OK, m.FinishOperation(session, OperationSign))
}

// TestClassicalSigningStillTakesTheTransportPath is the negative that bounds the
// routing predicate.
//
// The hooks sit in front of every C_SignInit and C_Sign in the module, so a
// predicate that was even slightly too broad would divert classical signing to
// a signer that cannot do RSA. The key here has an empty KeyID, which is the
// half of the predicate an ML-DSA key also satisfies; only the mechanism tells
// the two apart.
func TestClassicalSigningStillTakesTheTransportPath(t *testing.T) {
	message := []byte("RSA must still be signed by the backend")

	m, client := transportWatchingModule(t)
	defer m.Finalize()
	session := loginAsNormalUser(t, m)

	keyHandle, rv := m.CreateObject(session, []Attribute{
		NewUint32Attribute(CKA_CLASS, uint32(CKO_PRIVATE_KEY)),
		NewUint32Attribute(CKA_KEY_TYPE, uint32(CKK_RSA)),
		NewStringAttribute(CKA_LABEL, "classical-rsa"),
		NewBoolAttribute(CKA_SIGN, true),
		NewBoolAttribute(CKA_VERIFY, true),
		NewBoolAttribute(CKA_TOKEN, false),
	})
	require.Equal(t, CKR_OK, rv)

	require.Equal(t, CKR_OK, m.SignInit(session, &Mechanism{Type: CKM_RSA_PKCS}, keyHandle))
	signature, rv := m.Sign(session, message)
	require.Equal(t, CKR_OK, rv)

	assert.True(t, client.signCalled, "a classical signature must be produced by the backend")
	assert.Equal(t, []byte("mock-signature"), signature,
		"C_Sign must return what the transport answered, unchanged")
	require.Equal(t, CKR_OK, m.FinishOperation(session, OperationSign))

	// Multi-part classical signing must be untouched as well: the *Update and
	// *Final hooks sit in front of it too.
	client.signCalled = false
	require.Equal(t, CKR_OK, m.SignInit(session, &Mechanism{Type: CKM_RSA_PKCS}, keyHandle))
	require.Equal(t, CKR_OK, m.SignUpdate(session, message))
	signature, rv = m.SignFinal(session)
	require.Equal(t, CKR_OK, rv)
	assert.True(t, client.signCalled, "a classical multi-part signature must reach the backend")
	assert.Equal(t, []byte("mock-signature"), signature)
	require.Equal(t, CKR_OK, m.FinishOperation(session, OperationSign))
}

// TestClassicalVerificationStillTakesTheTransportPath is the C_Verify
// counterpart of TestClassicalSigningStillTakesTheTransportPath.
func TestClassicalVerificationStillTakesTheTransportPath(t *testing.T) {
	message := []byte("RSA must still be verified by the backend")

	m, client := transportWatchingModule(t)
	defer m.Finalize()
	session := loginAsNormalUser(t, m)

	keyHandle, rv := m.CreateObject(session, []Attribute{
		NewUint32Attribute(CKA_CLASS, uint32(CKO_PUBLIC_KEY)),
		NewUint32Attribute(CKA_KEY_TYPE, uint32(CKK_RSA)),
		NewAttribute(CKA_MODULUS, make([]byte, 256)),
		NewAttribute(CKA_PUBLIC_EXPONENT, []byte{0x01, 0x00, 0x01}),
		NewStringAttribute(CKA_LABEL, "classical-rsa-pub"),
		NewBoolAttribute(CKA_VERIFY, true),
		NewBoolAttribute(CKA_TOKEN, false),
	})
	require.Equal(t, CKR_OK, rv)

	require.Equal(t, CKR_OK, m.VerifyInit(session, &Mechanism{Type: CKM_RSA_PKCS}, keyHandle))
	assert.Equal(t, CKR_OK, m.Verify(session, message, []byte("mock-signature")))
	assert.True(t, client.verifyCalled, "a classical verification must be answered by the backend")

	client.verifyCalled = false
	require.Equal(t, CKR_OK, m.VerifyInit(session, &Mechanism{Type: CKM_RSA_PKCS}, keyHandle))
	require.Equal(t, CKR_OK, m.VerifyUpdate(session, message))
	assert.Equal(t, CKR_OK, m.VerifyFinal(session, []byte("mock-signature")))
	assert.True(t, client.verifyCalled, "a classical multi-part verification must reach the backend")
}

// TestMLDSAKeyNamingABackendKeyStillTakesTheTransportPath is the other half of
// the routing predicate.
//
// holdsOwnQuantumSignatureMaterial claims a key only when it names no backend
// key, so a backend that grows ML-DSA support later keeps working without a
// change here. The key in this test is a genuine ML-DSA object with material of
// its own; the only thing that sends it to the transport is its KeyID.
func TestMLDSAKeyNamingABackendKeyStillTakesTheTransportPath(t *testing.T) {
	m, client := transportWatchingModule(t)
	defer m.Finalize()
	session := loginAsNormalUser(t, m)

	_, priv := generatePQCKeyPair(t, m, session, CKM_ML_DSA_KEY_PAIR_GEN, "mldsa-backed",
		parameterSetAttribute(CKP_ML_DSA_65))

	// Name a backend key on the object. C_GenerateKeyPair leaves KeyID empty for
	// a pair this module generated, and no application-facing call sets it, so
	// the store is reached directly to model a key the daemon owns.
	obj, err := m.objectManager.getObjectUnchecked(priv)
	require.NoError(t, err)
	obj.KeyID = "backend-owned-mldsa-key"

	require.Equal(t, CKR_OK, m.SignInit(session, &Mechanism{Type: CKM_ML_DSA}, priv))
	signature, rv := m.Sign(session, []byte("this one belongs to the backend"))
	require.Equal(t, CKR_OK, rv)

	assert.True(t, client.signCalled, "an ML-DSA key that names a backend key must be signed with over the transport")
	require.NotNil(t, client.lastSignReq)
	assert.Equal(t, "backend-owned-mldsa-key", client.lastSignReq.KeyID,
		"the transport must be told which backend key to use")
	assert.Equal(t, []byte("mock-signature"), signature,
		"the answer must be the transport's, not an in-process ML-DSA signature")

	require.Equal(t, CKR_OK, m.FinishOperation(session, OperationSign))
}
