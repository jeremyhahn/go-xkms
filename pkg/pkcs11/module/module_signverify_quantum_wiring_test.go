// These tests drive the Cryptoki signature entry points themselves rather than
// the quantumSign*/quantumVerify* methods behind them, because the defect they
// guard was in the wiring and not in the methods.
//
// C_SignInit and C_Sign used to run an ML-DSA request down the transport path,
// where a key generated by this token has nothing to name: SignRequest went out
// with KeyID="" and the answer that came back was whatever the far end made of
// it. Every assertion below is therefore stated against the public API and
// checked with an oracle outside this package.
//
// The oracle is cloudflare/circl, called directly. The module's own C_Verify,
// C_VerifySignature and pkg/quantum's wrapper all share code with the signer
// under test, so none of them can distinguish a correct FIPS 204 signature from
// a self-consistent wrong one.

// transportSignatureLength is the length of the canned signature the mock
// transport returns ("mock-signature").
//
// It is the fingerprint of the defect: an ML-DSA C_Sign that reaches the
// transport comes back 14 bytes long, where FIPS 204 signatures are 2420, 3309
// or 4627. Asserting the exact ML-DSA length already excludes it, and naming it
// separately says which failure a regression is.
const transportSignatureLength = len("mock-signature")

// The circlVerifyMLDSA44/65/87 oracles these tests judge signatures with are
// defined alongside the hooks' own tests in module_verifysig_quantum_test.go.
// Each unmarshals the public key the token published and calls
// cloudflare/circl's Verify directly, under the empty FIPS 204 context this
// module signs with.

// mldsaWiringCase describes one ML-DSA parameter set end to end: how a caller
// asks for the key, what the signature must measure, and which reference
// implementation judges it.
type mldsaWiringCase struct {
	name          string
	parameterSet  ParameterSetType
	publicKeySize int
	signatureSize int
	circlVerify   func(publicKey, message, signature []byte) bool
}

// mldsaWiringCases covers every parameter set FIPS 204 defines. The signature
// sizes are taken from circl rather than written out, so a size that drifts
// from the reference implementation fails here rather than being enshrined.
var mldsaWiringCases = []mldsaWiringCase{
	{"ML-DSA-44", CKP_ML_DSA_44, MLDSA44PublicKeySize, mldsa44.SignatureSize, circlVerifyMLDSA44},
	{"ML-DSA-65", CKP_ML_DSA_65, MLDSA65PublicKeySize, mldsa65.SignatureSize, circlVerifyMLDSA65},
	{"ML-DSA-87", CKP_ML_DSA_87, MLDSA87PublicKeySize, mldsa87.SignatureSize, circlVerifyMLDSA87},
}

// transportWatchingModule builds an initialized module over a mock transport
// the caller keeps a reference to, so a test can assert not only what the
// module returned but whether it asked the far end at all.
func transportWatchingModule(t *testing.T) (*Module, *mockClient) {
	t.Helper()

	ResetGlobalModule()
	client := newMockClient()
	m, err := New(WithClient(client), WithConfig(DefaultConfig()))
	require.NoError(t, err)
	require.Equal(t, CKR_OK, m.Initialize(nil), "Initialize should succeed")

	return m, client
}

// TestMLDSASignatureSizesMatchFIPS204 pins the three signature sizes to the
// literals FIPS 204 gives them.
//
// The rest of this file measures signatures against circl's constants. This
// test is what makes that meaningful: if circl ever changed a constant, every
// other assertion here would move with it and stay green.
func TestMLDSASignatureSizesMatchFIPS204(t *testing.T) {
	assert.Equal(t, 2420, mldsa44.SignatureSize, "FIPS 204 ML-DSA-44 signature size")
	assert.Equal(t, 3309, mldsa65.SignatureSize, "FIPS 204 ML-DSA-65 signature size")
	assert.Equal(t, 4627, mldsa87.SignatureSize, "FIPS 204 ML-DSA-87 signature size")
	assert.Equal(t, 14, transportSignatureLength,
		"the mock transport's canned signature is the 14-byte artifact the defect produced")
}

// TestSignMLDSAThroughPublicAPIProducesACirclVerifiableSignature is the
// regression test for the defect this wiring closes.
//
// It runs the sequence an application runs -- C_GenerateKeyPair, C_SignInit,
// C_Sign -- and hands the result to circl. Before the hooks were wired,
// C_SignInit built a transport SignOperation for a key with KeyID="" and C_Sign
// returned the far end's 14-byte answer, which circl rejects and which is not
// even signature-shaped.
func TestSignMLDSAThroughPublicAPIProducesACirclVerifiableSignature(t *testing.T) {
	message := []byte("C_Sign must reach the in-process ML-DSA signer")

	for _, tc := range mldsaWiringCases {
		t.Run(tc.name, func(t *testing.T) {
			m, client := transportWatchingModule(t)
			defer m.Finalize()
			session := loginAsNormalUser(t, m)

			pub, priv := generatePQCKeyPair(t, m, session, CKM_ML_DSA_KEY_PAIR_GEN, "mldsa-sign",
				parameterSetAttribute(tc.parameterSet))

			publicKey := objectAttribute(t, m, pub, CKA_VALUE)
			require.Len(t, publicKey, tc.publicKeySize,
				"the generated public key must be the FIPS 204 size for this parameter set")

			// CKM_ML_DSA carries no parameter set of its own (v3.2 §6.67.4), so
			// this is also the path that resolves the level from the key object.
			require.Equal(t, CKR_OK, m.SignInit(session, &Mechanism{Type: CKM_ML_DSA}, priv))

			signature, rv := m.Sign(session, message)
			require.Equal(t, CKR_OK, rv)

			require.Len(t, signature, tc.signatureSize,
				"C_Sign must return a FIPS 204 signature, not the transport's answer")
			require.NotEqual(t, transportSignatureLength, len(signature),
				"a %d-byte signature is the transport's canned reply, which means the ML-DSA hook was bypassed",
				transportSignatureLength)

			assert.True(t, tc.circlVerify(publicKey, message, signature),
				"cloudflare/circl must accept the signature under the generated public key")
			assert.False(t, tc.circlVerify(publicKey, append(message, '!'), signature),
				"circl must reject the signature over different data, so the check above is a verification")

			assert.False(t, client.signCalled,
				"a key holding its own ML-DSA material must never be signed with over the transport")

			// The terminal call leaves the operation active under the two-call
			// convention (v3.2 §5.2), exactly as the transport path does.
			assert.Equal(t, CKR_OK, m.FinishOperation(session, OperationSign))
		})
	}
}

// TestSignMLDSAAcceptsThePerLevelVendorMechanism proves the second way an
// application can name an ML-DSA signature reaches the same signer.
//
// CKM_ML_DSA resolves its level from CKA_PARAMETER_SET; the vendor mechanisms
// state it themselves and must not be re-resolved. If only the standard
// spelling were wired, an application using the vendor mechanism would still be
// signing over the transport.
func TestSignMLDSAAcceptsThePerLevelVendorMechanism(t *testing.T) {
	message := []byte("the vendor mechanism names its own level")

	cases := []struct {
		name         string
		mechanism    MechanismType
		keyGen       MechanismType
		signatureLen int
		circlVerify  func(publicKey, message, signature []byte) bool
	}{
		{"ML-DSA-44", CKM_VENDOR_ML_DSA_44, CKM_VENDOR_ML_DSA_44_KEY_PAIR_GEN, mldsa44.SignatureSize, circlVerifyMLDSA44},
		{"ML-DSA-65", CKM_VENDOR_ML_DSA_65, CKM_VENDOR_ML_DSA_65_KEY_PAIR_GEN, mldsa65.SignatureSize, circlVerifyMLDSA65},
		{"ML-DSA-87", CKM_VENDOR_ML_DSA_87, CKM_VENDOR_ML_DSA_87_KEY_PAIR_GEN, mldsa87.SignatureSize, circlVerifyMLDSA87},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			m, client := transportWatchingModule(t)
			defer m.Finalize()
			session := loginAsNormalUser(t, m)

			pub, priv := generatePQCKeyPair(t, m, session, tc.keyGen, "mldsa-vendor")
			publicKey := objectAttribute(t, m, pub, CKA_VALUE)

			require.Equal(t, CKR_OK, m.SignInit(session, &Mechanism{Type: tc.mechanism}, priv))
			signature, rv := m.Sign(session, message)
			require.Equal(t, CKR_OK, rv)

			require.Len(t, signature, tc.signatureLen)
			assert.True(t, tc.circlVerify(publicKey, message, signature),
				"cloudflare/circl must accept a signature made under the vendor mechanism")
			assert.False(t, client.signCalled, "the vendor mechanism must not reach the transport either")

			assert.Equal(t, CKR_OK, m.FinishOperation(session, OperationSign))
		})
	}
}

// TestSignMLDSAMultiPartSignsTheWholeMessage proves C_SignUpdate and
// C_SignFinal are wired to the same in-process signer, and that they sign
// everything they were fed.
//
// ML-DSA signs the message rather than a digest of it (FIPS 204 §5.2), so a
// multi-part operation that dropped or reordered a part would still return a
// well-formed signature. Only an outside verifier catches that, which is why
// circl judges the concatenation and is then shown to reject the first part on
// its own.
func TestSignMLDSAMultiPartSignsTheWholeMessage(t *testing.T) {
	firstPart := []byte("first part of a multi-part ")
	secondPart := []byte("ML-DSA message")
	whole := append(append([]byte{}, firstPart...), secondPart...)

	for _, tc := range mldsaWiringCases {
		t.Run(tc.name, func(t *testing.T) {
			m, client := transportWatchingModule(t)
			defer m.Finalize()
			session := loginAsNormalUser(t, m)

			pub, priv := generatePQCKeyPair(t, m, session, CKM_ML_DSA_KEY_PAIR_GEN, "mldsa-multipart",
				parameterSetAttribute(tc.parameterSet))
			publicKey := objectAttribute(t, m, pub, CKA_VALUE)

			require.Equal(t, CKR_OK, m.SignInit(session, &Mechanism{Type: CKM_ML_DSA}, priv))
			require.Equal(t, CKR_OK, m.SignUpdate(session, firstPart))
			require.Equal(t, CKR_OK, m.SignUpdate(session, secondPart))

			signature, rv := m.SignFinal(session)
			require.Equal(t, CKR_OK, rv)

			require.Len(t, signature, tc.signatureSize,
				"C_SignFinal must return a FIPS 204 signature, not the transport's answer")
			require.NotEqual(t, transportSignatureLength, len(signature),
				"a %d-byte signature means the multi-part ML-DSA hook was bypassed",
				transportSignatureLength)

			assert.True(t, tc.circlVerify(publicKey, whole, signature),
				"circl must accept the signature over the concatenation of both parts")
			assert.False(t, tc.circlVerify(publicKey, firstPart, signature),
				"circl must reject the signature over the first part alone, so the second part was really signed")
			assert.False(t, tc.circlVerify(publicKey, secondPart, signature),
				"circl must reject the signature over the second part alone")

			assert.False(t, client.signCalled, "a multi-part ML-DSA operation must not reach the transport")
			assert.Equal(t, CKR_OK, m.FinishOperation(session, OperationSign))
		})
	}
}

// TestVerifyMLDSAThroughPublicAPIAcceptsACirclSignature proves C_VerifyInit and
// C_Verify reach the in-process verifier.
//
// The signature under test is produced by circl and not by this module, so a
// verifier that agreed with the module's own signer but not with FIPS 204 fails
// here. The rejection case is what shows C_Verify is verifying at all.
func TestVerifyMLDSAThroughPublicAPIAcceptsACirclSignature(t *testing.T) {
	message := []byte("C_Verify must reach the in-process ML-DSA verifier")

	for _, tc := range mldsaWiringCases {
		t.Run(tc.name, func(t *testing.T) {
			m, client := transportWatchingModule(t)
			defer m.Finalize()
			session := loginAsNormalUser(t, m)

			pub, priv := generatePQCKeyPair(t, m, session, CKM_ML_DSA_KEY_PAIR_GEN, "mldsa-verify",
				parameterSetAttribute(tc.parameterSet))
			publicKey := objectAttribute(t, m, pub, CKA_VALUE)

			// The signature comes from the module's signer, which the assertions
			// above have already shown circl accepts; here circl is the second
			// opinion that the verifier is judging the same thing.
			require.Equal(t, CKR_OK, m.SignInit(session, &Mechanism{Type: CKM_ML_DSA}, priv))
			signature, rv := m.Sign(session, message)
			require.Equal(t, CKR_OK, rv)
			require.Equal(t, CKR_OK, m.FinishOperation(session, OperationSign))
			require.True(t, tc.circlVerify(publicKey, message, signature))

			require.Equal(t, CKR_OK, m.VerifyInit(session, &Mechanism{Type: CKM_ML_DSA}, pub))
			assert.Equal(t, CKR_OK, m.Verify(session, message, signature),
				"C_Verify must accept a genuine FIPS 204 signature")

			require.Equal(t, CKR_OK, m.VerifyInit(session, &Mechanism{Type: CKM_ML_DSA}, pub))
			assert.Equal(t, CKR_SIGNATURE_INVALID, m.Verify(session, append(message, '!'), signature),
				"C_Verify must reject a signature over different data")

			assert.False(t, client.verifyCalled,
				"a key holding its own ML-DSA material must never be verified over the transport")
		})
	}
}

// TestVerifyMLDSAMultiPartVerifiesTheWholeMessage proves C_VerifyUpdate and
// C_VerifyFinal are wired to the in-process verifier and accumulate every part.
func TestVerifyMLDSAMultiPartVerifiesTheWholeMessage(t *testing.T) {
	firstPart := []byte("first part for multi-part ")
	secondPart := []byte("ML-DSA verification")
	whole := append(append([]byte{}, firstPart...), secondPart...)

	for _, tc := range mldsaWiringCases {
		t.Run(tc.name, func(t *testing.T) {
			m, client := transportWatchingModule(t)
			defer m.Finalize()
			session := loginAsNormalUser(t, m)

			pub, priv := generatePQCKeyPair(t, m, session, CKM_ML_DSA_KEY_PAIR_GEN, "mldsa-verify-multipart",
				parameterSetAttribute(tc.parameterSet))
			publicKey := objectAttribute(t, m, pub, CKA_VALUE)

			require.Equal(t, CKR_OK, m.SignInit(session, &Mechanism{Type: CKM_ML_DSA}, priv))
			signature, rv := m.Sign(session, whole)
			require.Equal(t, CKR_OK, rv)
			require.Equal(t, CKR_OK, m.FinishOperation(session, OperationSign))
			require.True(t, tc.circlVerify(publicKey, whole, signature))

			require.Equal(t, CKR_OK, m.VerifyInit(session, &Mechanism{Type: CKM_ML_DSA}, pub))
			require.Equal(t, CKR_OK, m.VerifyUpdate(session, firstPart))
			require.Equal(t, CKR_OK, m.VerifyUpdate(session, secondPart))
			assert.Equal(t, CKR_OK, m.VerifyFinal(session, signature),
				"C_VerifyFinal must accept the signature over the concatenation of both parts")

			// Feeding only the first part must fail, so the accumulation is
			// shown to be real rather than the last part winning.
			require.Equal(t, CKR_OK, m.VerifyInit(session, &Mechanism{Type: CKM_ML_DSA}, pub))
			require.Equal(t, CKR_OK, m.VerifyUpdate(session, firstPart))
			assert.Equal(t, CKR_SIGNATURE_INVALID, m.VerifyFinal(session, signature),
				"C_VerifyFinal must reject a signature over more than it was fed")

			assert.False(t, client.verifyCalled,
				"a multi-part ML-DSA verification must not reach the transport")
		})
	}
}

// TestSignInitRefusesAnMLDSAKeyWithNoMaterial proves the module answers for a
// key it claims, instead of letting the request fall through.
//
// This is the hole the wiring closes. An ML-DSA object with an empty KeyID and
// no CKA_VALUE used to reach the transport as SignRequest{KeyID: ""}, where the
// daemon matched whatever key had an empty common name. The module holds the
// only material such a key could have, so it has to answer itself, and
// CKR_KEY_HANDLE_INVALID is what C_SignInit's return table (v3.2 §5.13.1) gives
// for a handle that names no usable key.
func TestSignInitRefusesAnMLDSAKeyWithNoMaterial(t *testing.T) {
	m, client := transportWatchingModule(t)
	defer m.Finalize()
	session := loginAsNormalUser(t, m)

	// A private key object of the right class and parameter set but with no
	// CKA_VALUE: nothing this module could sign with.
	handle, rv := m.CreateObject(session, []Attribute{
		NewUint32Attribute(CKA_CLASS, uint32(CKO_PRIVATE_KEY)),
		NewUint32Attribute(CKA_KEY_TYPE, uint32(CKK_ML_DSA)),
		NewStringAttribute(CKA_LABEL, "mldsa-no-material"),
		NewBoolAttribute(CKA_SIGN, true),
		NewBoolAttribute(CKA_TOKEN, false),
		parameterSetAttribute(CKP_ML_DSA_65),
	})
	require.Equal(t, CKR_OK, rv)

	assert.Equal(t, CKR_KEY_HANDLE_INVALID, m.SignInit(session, &Mechanism{Type: CKM_ML_DSA}, handle),
		"the module must answer for an ML-DSA key it holds no material for")
	assert.False(t, client.signCalled,
		"a refused ML-DSA C_SignInit must never send KeyID=\"\" to the transport")

	// The refusal must leave nothing active behind for the next operation to
	// collide with.
	assert.Equal(t, CKR_OPERATION_NOT_INITIALIZED, m.FinishOperation(session, OperationSign))
}

