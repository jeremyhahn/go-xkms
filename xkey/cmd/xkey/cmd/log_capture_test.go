package cmd

import (
	"bytes"
	"log/slog"
	"testing"
)

// captureDefaultLog temporarily replaces slog's default logger with one
// that writes to the returned buffer, and restores the previous default
// when the test ends. It has no build tag because both ble-tagged tests
// (device_pair_flow_test.go) and untagged tests (oath_barrier_test.go,
// oidc_barrier_test.go) call it.
func captureDefaultLog(t *testing.T) *bytes.Buffer {
	t.Helper()
	var buf bytes.Buffer
	previous := slog.Default()
	slog.SetDefault(slog.New(slog.NewTextHandler(&buf, nil)))
	t.Cleanup(func() { slog.SetDefault(previous) })
	return &buf
}
