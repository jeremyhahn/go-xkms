// stubCAService is a minimal agent.CAService for tests that submit and
// approve enrollment requests without a network round trip.
type stubCAService struct{}

func (s *stubCAService) SignCSR(csrPEM []byte) ([]byte, error) {
	return cliTestCertPEMForCSR(csrPEM, 42), nil
}

func (s *stubCAService) GetCACertificate() ([]byte, error) {
	return []byte("-----BEGIN CERTIFICATE-----\nfake-ca\n-----END CERTIFICATE-----\n"), nil
}

func (s *stubCAService) RevokeCertificate(string) error { return nil }

func (s *stubCAService) IsRevoked(string) (bool, error) { return false, nil }

// testCSRForAgentCLI generates a fresh CSR for enrollment-submission tests.
func testCSRForAgentCLI(t *testing.T) []byte {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatalf("generate key: %v", err)
	}
	template := &x509.CertificateRequest{
		Subject: pkix.Name{CommonName: "test-agent"},
	}
	csrDER, err := x509.CreateCertificateRequest(rand.Reader, template, key)
	if err != nil {
		t.Fatalf("create CSR: %v", err)
	}
	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE REQUEST", Bytes: csrDER})
}

// cliTestCertPEMForCSR mints a real, parseable certificate PEM that embeds
// the given CSR's own public key, standing in for what a real CA returns
// from SignCSR.
func cliTestCertPEMForCSR(csrPEM []byte, serial int64) []byte {
	block, _ := pem.Decode(csrPEM)
	if block == nil {
		panic("cliTestCertPEMForCSR: CSR is not PEM")
	}
	csr, err := x509.ParseCertificateRequest(block.Bytes)
	if err != nil {
		panic(err)
	}
	signerKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		panic(err)
	}
	template := &x509.Certificate{
		SerialNumber: big.NewInt(serial),
		Subject:      csr.Subject,
		NotBefore:    time.Now().Add(-time.Minute),
		NotAfter:     time.Now().Add(time.Hour),
		KeyUsage:     x509.KeyUsageDigitalSignature,
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, csr.PublicKey, signerKey)
	if err != nil {
		panic(err)
	}
	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})
}
