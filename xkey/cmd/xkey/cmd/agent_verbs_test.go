// TestRunAgentCode_PersistsAcrossInvocations proves the code generated by
// "xkey agent code" survives to a separate, independent EnrollmentService
// instance backed by the same on-disk store - simulating a code generated
// by one CLI invocation being honored by a separately running "agent
// start" process, the requirement the process-scoping limitation used to
// prevent.
func TestRunAgentCode_PersistsAcrossInvocations(t *testing.T) {
	withAgentCLIFixture(t)
	agentCodeJSON = true
	t.Cleanup(func() { agentCodeJSON = false })

	out, err := runDetached(t, runAgentCode)
	if err != nil {
		t.Fatalf("runAgentCode: %v", err)
	}
	var info services.EnrollmentCodeInfo
	if err := json.Unmarshal([]byte(out), &info); err != nil {
		t.Fatalf("decode code: %v", err)
	}

	enrollment := independentEnrollmentService(t, agent.EnrollOneTimeCode)
	if _, _, err := enrollment.EnrollWithCode(info.Code, testCSRForAgentCLI(t)); err != nil {
		t.Fatalf("a code generated by \"xkey agent code\" was not honored by a separate process reading the same store: %v", err)
	}
}

