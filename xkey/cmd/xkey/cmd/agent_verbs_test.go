// independentEnrollmentService builds an agent.EnrollmentService backed by
// the real on-disk store "xkey agent" commands use in this test - the
// same directory newCLIAgentService resolves via agentStoreDir() - but
// with its own store and CA Go values, so it shares no memory with any
// EnrollmentService a command under test built. This is what proves
// persistence rather than in-process sharing: state only crosses between
// this and a command's own instance through the store.
func independentEnrollmentService(t *testing.T, methods ...agent.EnrollmentMethod) *agent.EnrollmentService {
	t.Helper()

	store, err := agent.NewFileStore(mustAgentStoreDir(t), slog.Default())
	if err != nil {
		t.Fatalf("NewFileStore: %v", err)
	}
	cfg := agent.DefaultConfig()
	cfg.EnrollmentMethods = methods

	enrollment, err := agent.NewEnrollmentService(cfg, &stubCAService{}, store, slog.Default())
	if err != nil {
		t.Fatalf("NewEnrollmentService: %v", err)
	}
	return enrollment
}

