// stubbedAgentService substitutes newCLIAgentServiceFunc with a service
// built directly in the test against an in-memory store and a stub CA, so
// tests that only care about command-level formatting and error mapping
// do not need a fake xkmsd endpoint or the filesystem. It returns the
// backing EnrollmentService too, so a test can seed or inspect state
// directly. See independentEnrollmentService for the complementary
// cross-process persistence tests, and newCLIAgentServiceFunc's doc
// comment for why this seam exists at all.
func stubbedAgentService(t *testing.T) (*services.AgentService, *agent.EnrollmentService) {
	t.Helper()

	cfg := agent.DefaultConfig()
	cfg.EnrollmentMethods = []agent.EnrollmentMethod{
		agent.EnrollOneTimeCode,
		agent.EnrollAdminApproval,
	}
	store := agent.NewMemoryStore()
	ca := &stubCAService{}
	enrollment, err := agent.NewEnrollmentService(cfg, ca, store, slog.Default())
	if err != nil {
		t.Fatalf("NewEnrollmentService: %v", err)
	}

	svc := services.NewAgentService()
	svc.SetEnrollmentService(enrollment)
	svc.SetEnrollmentStore(store)

	previous := newCLIAgentServiceFunc
	newCLIAgentServiceFunc = func(*cobra.Command) (*services.AgentService, func(), error) {
		return svc, func() {}, nil
	}
	t.Cleanup(func() { newCLIAgentServiceFunc = previous })

	return svc, enrollment
}

