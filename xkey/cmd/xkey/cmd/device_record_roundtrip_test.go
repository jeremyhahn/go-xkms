// testdata/devices_cli_fixture.yaml is byte-for-byte what the pre-#130(b)
// CLI PairedDevice struct produced: it was generated by marshaling sample
// data through that exact struct definition (field names, yaml tags and
// field order) before it was replaced by the alias to pairing.PairedDevice,
// so this test is pinned against the CLI's own historical output rather
// than against a hand-written approximation of it.
//
// #130(b) unified the CLI's, the GUI's and pkg/pairing's device-record
// structs into one type owned by pkg/pairing. The CLI's field order was
// carried forward unchanged (see pairing.PairedDevice's field declaration
// order), so a devices.yaml written by the pre-unification CLI round-trips
// through the unified type byte-for-byte.
func TestDevicesConfigRoundTripsTheCLIFixtureByteIdentical(t *testing.T) {
	original, err := os.ReadFile("testdata/devices_cli_fixture.yaml")
	require.NoError(t, err)

	var cfg DevicesConfig
	require.NoError(t, yaml.Unmarshal(original, &cfg))

	require.Len(t, cfg.Devices, 2)
	bound := cfg.Devices[0]
	assert.Equal(t, "Pixel 9 Pro Fold", bound.Name)
	assert.Equal(t, "AA:BB:CC:DD:EE:01", bound.Address)
	assert.Equal(t, "cGhvbmUtcHVibGljLWtleS1iYXNlNjQ=", bound.NoisePublicKey)
	assert.Equal(t, "bG9jYWwtcHJpdmF0ZS1rZXktYmFzZTY0", bound.LocalNoisePrivateKey)
	assert.True(t, bound.PairedAt.Equal(time.Date(2026, 3, 15, 10, 30, 0, 0, time.UTC)))
	assert.True(t, bound.LastDeviceAttestationTime.Equal(time.Date(2026, 3, 15, 10, 31, 5, 0, time.UTC)))
	assert.Equal(t, "deadbeefcafef00d", bound.DeviceBootHashHex)
	assert.Equal(t, 30*time.Minute, time.Duration(bound.AttestationGracePeriod))
	assert.Equal(t, "strongbox", bound.SecurityLevel)
	assert.True(t, bound.BootStateVerified)
	assert.Equal(t, "aabbccddeeff00112233445566778899aabbccddeeff00112233445566778899", bound.DeviceFingerprint)
	assert.Equal(t, 2, bound.AttestationProtocolVersion)
	// Fields the pre-unification CLI struct never carried: round-tripping
	// through the unified type must not invent values for them.
	assert.Nil(t, bound.LastAttestation)
	assert.Nil(t, bound.AttestationPolicy)
	assert.False(t, bound.IsBackend)

	legacy := cfg.Devices[1]
	assert.Equal(t, "Legacy Phone", legacy.Name)
	assert.Zero(t, legacy.AttestationProtocolVersion)

	require.NotNil(t, cfg.AttestationPolicy)
	assert.Equal(t, 5*time.Minute, time.Duration(cfg.AttestationPolicy.DefaultGracePeriod))
	assert.True(t, cfg.AttestationPolicy.RequireDeviceAttestation)
	assert.Equal(t, "tee", cfg.AttestationPolicy.MinSecurityLevel)

	resaved, err := yaml.Marshal(&cfg)
	require.NoError(t, err)

	assert.Equal(t, string(original), string(resaved),
		"the unified type carries the CLI's own field order forward, so a devices.yaml "+
			"the pre-unification CLI wrote must re-save unchanged, byte for byte")
}
