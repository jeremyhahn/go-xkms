// ErrPIVSoftwareKeyStoreRequiresBarrier is returned when the software PIV
// backend is used before xKey's key store exists: its keys live in that
// store, encrypted at rest by the barrier, so without one a generated key
// would not outlive the command that made it.
var ErrPIVSoftwareKeyStoreRequiresBarrier = errors.New(
	"piv: the software backend keeps its keys in xKey's encrypted key store; run \"xkey barrier init\" first")

// ensureSoftwarePIVKeyStore backs the software PIV backend with xKey's key
// store -- the barrier-protected "keys/" namespace and xkms software backend
// the GUI and the vault key factors use (localKeyBackends) -- and routes PIV
// key generation and signing through it (the same resolver the PKCS#11
// backend installs). A key generated by one xkey command is then the key the
// next one signs with, encrypted at rest between them.
func ensureSoftwarePIVKeyStore(cmd *cobra.Command, logger *slog.Logger) error {
	home, err := xhome.Resolve()
	if err != nil {
		return &SentinelCauseError{Sentinel: ErrPIVSoftwareKeyStoreRequiresBarrier, Cause: err}
	}
	dataDir, err := home.EnsureDataDir()
	if err != nil {
		return &SentinelCauseError{Sentinel: ErrPIVSoftwareKeyStoreRequiresBarrier, Cause: err}
	}
	if !barrierRootKeyExists(dataDir) {
		return ErrPIVSoftwareKeyStoreRequiresBarrier
	}
	if _, err := localKeyBackends(cmd); err != nil {
		return err
	}
	svc, err := xkms.Get()
	if err != nil {
		return err
	}
	logger.Debug("software PIV keys in xKey's key store")
	return svc.InitPIVBackendResolver()
}
