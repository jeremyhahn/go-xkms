// CAService is the interface for certificate authority operations used
// by the enrollment service. Implementations must be safe for concurrent use.
type CAService interface {
	// SignCSR signs a PEM-encoded PKCS#10 certificate signing request and
	// returns the signed certificate as PEM.
	SignCSR(csrPEM []byte) (certPEM []byte, err error)

	// GetCACertificate returns the CA certificate as PEM-encoded bytes.
	GetCACertificate() ([]byte, error)

	// RevokeCertificate revokes a certificate identified by its serial number.
	RevokeCertificate(serialNumber string) error

	// IsRevoked reports whether the certificate identified by its serial
	// number has been revoked. Callers must fail closed when this returns
	// an error: an indeterminate revocation status is never treated as
	// "not revoked".
	IsRevoked(serialNumber string) (bool, error)
}

// EnrollmentStore persists enrolled agent state, outstanding one-time
// enrollment codes, and pending admin-approval requests. Implementations
// must be safe for concurrent use, including across separate processes
// sharing the same backing storage (a code generated by one process must
// be consumable by another reading the same store).
type EnrollmentStore interface {
	// SaveAgent persists an agent record, creating or updating as needed.
	SaveAgent(agent *AgentInfo) error

	// GetAgent retrieves an agent by its ID. Returns ErrAgentNotFound
	// if the agent does not exist.
	GetAgent(id string) (*AgentInfo, error)

	// ListAgents returns all enrolled agents.
	ListAgents() ([]*AgentInfo, error)

	// DeleteAgent removes an agent by its ID. Returns ErrAgentNotFound
	// if the agent does not exist.
	DeleteAgent(id string) error

	// SaveCode persists a one-time enrollment code, identified by the
	// hex-encoded SHA-256 hash of the code value. The code's plaintext
	// value is never passed to the store and must never be persisted by
	// an implementation: only the hash and its expiry are.
	SaveCode(hash string, expiresAt time.Time) error

	// ConsumeCode atomically validates and single-use-consumes the code
	// identified by hash. Among any number of callers racing to consume
	// the same hash - including callers in separate processes sharing the
	// same backing storage - at most one observes success; every other
	// caller, and any later caller, observes ErrEnrollmentCodeInvalid, as
	// if the code had never existed. Returns ErrEnrollmentCodeInvalid if
	// no matching code exists, or ErrEnrollmentCodeExpired if it existed
	// but had already expired (the expired code is consumed regardless,
	// so it cannot be retried).
	ConsumeCode(hash string) error

	// CleanExpiredCodes removes every expired, unconsumed code and
	// reports how many were removed.
	CleanExpiredCodes() (int, error)

	// SavePending persists a pending enrollment request, creating or
	// updating as needed.
	SavePending(p *PendingEnrollment) error

	// GetPending retrieves a pending enrollment request by its ID.
	// Returns ErrRequestNotFound if it does not exist.
	GetPending(id string) (*PendingEnrollment, error)

	// ListPending returns every persisted pending enrollment request,
	// regardless of status.
	ListPending() ([]*PendingEnrollment, error)

	// DeletePending removes a pending enrollment request by its ID.
	// Returns ErrRequestNotFound if it does not exist.
	DeletePending(id string) error
}

// AgentInfo describes an enrolled remote agent.
type AgentInfo struct {
	// ID is a unique identifier for the agent derived from the certificate
	// fingerprint.
	ID string `json:"id"`

	// Name is a human-readable name assigned during enrollment.
	Name string `json:"name"`

	// Address is the last known address of the agent.
	Address string `json:"address"`

	// CertificateFingerprint is the SHA-256 fingerprint of the agent's
	// certificate in hex-encoded form.
	CertificateFingerprint string `json:"certificate_fingerprint"`

	// CertificateSerial is the serial number of the certificate the CA
	// issued for this agent, hex-encoded with no leading zero padding
	// (big.Int.Text(16)). It is what RemoveAgent and the connection-time
	// revocation check present to the CA's RevokeCertificate and
	// IsRevoked calls.
	CertificateSerial string `json:"certificate_serial"`

	// EnrolledAt is the time the agent was enrolled.
	EnrolledAt time.Time `json:"enrolled_at"`

	// LastSeen is the time the agent was last seen connected.
	LastSeen time.Time `json:"last_seen"`

	// Status describes the current enrollment status (e.g., "active",
	// "revoked").
	Status string `json:"status"`
}

// OneTimeCode is a short-lived enrollment code generated by the master.
type OneTimeCode struct {
	// Code is the random code string presented by the agent.
	Code string `json:"code"`

	// ExpiresAt is the time after which the code is no longer valid.
	ExpiresAt time.Time `json:"expires_at"`

	// Used marks whether this code has been consumed.
	Used bool `json:"used"`
}

// PendingEnrollment represents an enrollment request awaiting admin
// approval. It is persisted through EnrollmentStore for the lifetime of
// the request and deleted on approval or rejection - there is no
// "rejected" resting state to query later; RejectEnrollment's reason is
// logged and emitted as an event at the time of rejection, not retained.
type PendingEnrollment struct {
	// ID is a unique identifier for this enrollment request.
	ID string `json:"id"`

	// CSR is the PEM-encoded certificate signing request.
	CSR []byte `json:"csr"`

	// Fingerprint is the SHA-256 fingerprint of the CSR public key.
	Fingerprint string `json:"fingerprint"`

	// RequestedAt is the time the request was submitted.
	RequestedAt time.Time `json:"requested_at"`

	// Status is the current state: "pending" or "approved". "approved" is
	// a brief transitional state written before the CSR is signed, so a
	// concurrent second approval attempt is rejected rather than
	// double-processed; the record is deleted once approval completes.
	Status string `json:"status"`
}

// EnrollmentService manages agent enrollment and certificate issuance.
// It supports all four enrollment methods and enforces the enrollment
// policy from the Config. All mutable state - agents, one-time codes, and
// pending requests - lives in the EnrollmentStore, so EnrollmentService
// itself holds no locks: any number of instances, in any number of
// processes, backed by the same store observe and mutate the same state.
// Thread-safe (and multi-process-safe, to the extent the store is).
type EnrollmentService struct {
	config *Config
	ca     CAService
	store  EnrollmentStore
	logger *slog.Logger
}

// NewEnrollmentService creates a new EnrollmentService. Returns an error
// if any required parameter is nil.
func NewEnrollmentService(cfg *Config, ca CAService, store EnrollmentStore, logger *slog.Logger) (*EnrollmentService, error) {
	if cfg == nil {
		return nil, ErrNilConfig
	}
	if ca == nil {
		return nil, ErrNilCAService
	}
	if store == nil {
		return nil, ErrNilEnrollmentStore
	}
	if logger == nil {
		return nil, ErrNilLogger
	}
	return &EnrollmentService{
		config: cfg,
		ca:     ca,
		store:  store,
		logger: logger,
	}, nil
}

// GenerateOneTimeCode creates a short-lived enrollment code. The validity
// duration determines how long the code is usable. If validity is zero,
// the configured default is used. Only the code's SHA-256 hash is
// persisted through the EnrollmentStore; the plaintext code is returned to
// the caller and never stored anywhere, so a compromised store cannot be
// used to redeem outstanding codes. Because the hash - not the process's
// memory - is the code's only record, a code generated by one
// EnrollmentService instance is honored by any other instance backed by
// the same store, including one running as a separate process.
func (s *EnrollmentService) GenerateOneTimeCode(validity time.Duration) (*OneTimeCode, error) {
	if !s.IsMethodAllowed(EnrollOneTimeCode) {
		return nil, ErrEnrollmentMethodNotAllowed
	}

	if validity <= 0 {
		validity = s.config.OneTimeCodeValidity
	}

	code, err := generateSecureCode(s.config.OneTimeCodeLength)
	if err != nil {
		return nil, &AgentError{Operation: "generate_code", Err: err}
	}

	expiresAt := time.Now().Add(validity)
	if err := s.store.SaveCode(hashCode(code), expiresAt); err != nil {
		return nil, &AgentError{Operation: "generate_code", Err: err}
	}

	otc := &OneTimeCode{
		Code:      code,
		ExpiresAt: expiresAt,
		Used:      false,
	}

	s.logger.Info("generated one-time enrollment code",
		"expires_at", otc.ExpiresAt.Format(time.RFC3339))

	return otc, nil
}

// EnrollWithCode validates a one-time code and issues a certificate for
// the provided CSR. Returns the signed certificate PEM and the CA
// certificate PEM.
func (s *EnrollmentService) EnrollWithCode(code string, csrPEM []byte) (certPEM, caPEM []byte, err error) {
	if !s.IsMethodAllowed(EnrollOneTimeCode) {
		return nil, nil, ErrEnrollmentMethodNotAllowed
	}
	if len(csrPEM) == 0 {
		return nil, nil, ErrInvalidCSR
	}

	// Consuming the code is the single-use gate: the store guarantees at
	// most one caller observes success for a given code, even across
	// processes, so this line is where a replayed or raced code is
	// rejected.
	if err := s.store.ConsumeCode(hashCode(code)); err != nil {
		return nil, nil, err
	}

	// Check max agents limit.
	if err := s.checkMaxAgents(); err != nil {
		return nil, nil, err
	}

	// Validate the CSR.
	fingerprint, err := csrFingerprint(csrPEM)
	if err != nil {
		return nil, nil, &AgentError{Operation: "enroll_with_code", Err: err}
	}

	// Sign the CSR.
	certPEM, err = s.ca.SignCSR(csrPEM)
	if err != nil {
		return nil, nil, &AgentError{Operation: "enroll_with_code", Err: err}
	}

	// Record the serial number of the issued certificate so it can be
	// revoked later, either directly or when the agent is removed.
	serial, err := certificateSerialHex(certPEM)
	if err != nil {
		return nil, nil, &AgentError{Operation: "enroll_with_code", Err: ErrCertificateInvalid, Cause: err}
	}

	// Get CA certificate.
	caPEM, err = s.ca.GetCACertificate()
	if err != nil {
		return nil, nil, &AgentError{Operation: "enroll_with_code", Err: err}
	}

	// Record the enrollment.
	agentInfo := &AgentInfo{
		ID:                     fingerprint,
		Name:                   "agent-" + fingerprint[:8],
		CertificateFingerprint: fingerprint,
		CertificateSerial:      serial,
		EnrolledAt:             time.Now(),
		LastSeen:               time.Now(),
		Status:                 "active",
	}
	if storeErr := s.store.SaveAgent(agentInfo); storeErr != nil {
		s.logger.Warn("failed to persist agent enrollment",
			"fingerprint", fingerprint,
			"error", storeErr)
	}

	s.logger.Info("agent enrolled via one-time code",
		"agent_id", agentInfo.ID)

	return certPEM, caPEM, nil
}

// SubmitEnrollmentRequest submits a CSR for admin approval. Returns the
// request ID that the administrator uses to approve or reject the request.
func (s *EnrollmentService) SubmitEnrollmentRequest(csrPEM []byte) (string, error) {
	if !s.IsMethodAllowed(EnrollAdminApproval) {
		return "", ErrEnrollmentMethodNotAllowed
	}
	if len(csrPEM) == 0 {
		return "", ErrInvalidCSR
	}

	// Check max agents limit.
	if err := s.checkMaxAgents(); err != nil {
		return "", err
	}

	fingerprint, err := csrFingerprint(csrPEM)
	if err != nil {
		return "", &AgentError{Operation: "submit_enrollment", Err: err}
	}

	requestID, err := generateSecureCode(16)
	if err != nil {
		return "", &AgentError{Operation: "submit_enrollment", Err: err}
	}

	pending := &PendingEnrollment{
		ID:          requestID,
		CSR:         csrPEM,
		Fingerprint: fingerprint,
		RequestedAt: time.Now(),
		Status:      "pending",
	}

	if err := s.store.SavePending(pending); err != nil {
		return "", &AgentError{Operation: "submit_enrollment", Err: err}
	}

	s.logger.Info("enrollment request submitted",
		"request_id", requestID,
		"fingerprint", fingerprint)

	return requestID, nil
}

// ApproveEnrollment approves a pending enrollment request, signs the CSR,
// and returns the signed certificate PEM and CA certificate PEM. The
// request is deleted from the store once approval completes; there is no
// "approved" resting record to query afterward, only the resulting
// AgentInfo.
func (s *EnrollmentService) ApproveEnrollment(requestID string) (certPEM, caPEM []byte, err error) {
	if requestID == "" {
		return nil, nil, ErrInvalidRequestID
	}

	pending, err := s.store.GetPending(requestID)
	if err != nil {
		return nil, nil, ErrRequestNotFound
	}
	if pending.Status != "pending" {
		return nil, nil, ErrEnrollmentFailed
	}

	// Mark the request as being processed before signing, so a second,
	// concurrent approval attempt for the same request - from this
	// instance or another sharing the store - sees a non-"pending" status
	// and is rejected rather than double-signing the CSR.
	pending.Status = "approved"
	if err := s.store.SavePending(pending); err != nil {
		return nil, nil, &AgentError{Operation: "approve_enrollment", Err: err}
	}

	// Sign the CSR.
	certPEM, err = s.ca.SignCSR(pending.CSR)
	if err != nil {
		return nil, nil, &AgentError{Operation: "approve_enrollment", Err: err}
	}

	// Record the serial number of the issued certificate so it can be
	// revoked later, either directly or when the agent is removed.
	serial, err := certificateSerialHex(certPEM)
	if err != nil {
		return nil, nil, &AgentError{Operation: "approve_enrollment", Err: ErrCertificateInvalid, Cause: err}
	}

	// Get CA certificate.
	caPEM, err = s.ca.GetCACertificate()
	if err != nil {
		return nil, nil, &AgentError{Operation: "approve_enrollment", Err: err}
	}

	// Record the enrollment.
	agentInfo := &AgentInfo{
		ID:                     pending.Fingerprint,
		Name:                   "agent-" + pending.Fingerprint[:8],
		CertificateFingerprint: pending.Fingerprint,
		CertificateSerial:      serial,
		EnrolledAt:             time.Now(),
		LastSeen:               time.Now(),
		Status:                 "active",
	}
	if storeErr := s.store.SaveAgent(agentInfo); storeErr != nil {
		s.logger.Warn("failed to persist agent enrollment",
			"fingerprint", pending.Fingerprint,
			"error", storeErr)
	}

	if err := s.store.DeletePending(requestID); err != nil {
		s.logger.Warn("failed to remove approved pending request",
			"request_id", requestID, "error", err)
	}

	s.logger.Info("enrollment approved",
		"request_id", requestID,
		"agent_id", agentInfo.ID)

	return certPEM, caPEM, nil
}

// RejectEnrollment rejects a pending enrollment request, deleting it from
// the store. reason is logged and reported to the caller for an audit
// trail or UI event; it is not persisted, since the record it would
// describe no longer exists once this returns.
func (s *EnrollmentService) RejectEnrollment(requestID string, reason string) error {
	if requestID == "" {
		return ErrInvalidRequestID
	}

	pending, err := s.store.GetPending(requestID)
	if err != nil {
		return ErrRequestNotFound
	}
	if pending.Status != "pending" {
		return ErrEnrollmentFailed
	}

	if err := s.store.DeletePending(requestID); err != nil {
		return &AgentError{Operation: "reject_enrollment", Err: err}
	}

	s.logger.Info("enrollment rejected",
		"request_id", requestID,
		"reason", reason)

	return nil
}

// ListPending returns every pending enrollment request.
func (s *EnrollmentService) ListPending() ([]*PendingEnrollment, error) {
	pending, err := s.store.ListPending()
	if err != nil {
		return nil, &AgentError{Operation: "list_pending", Err: err}
	}

	result := make([]*PendingEnrollment, 0, len(pending))
	for _, p := range pending {
		if p.Status == "pending" {
			result = append(result, p)
		}
	}
	return result, nil
}

// IsMethodAllowed checks if an enrollment method is allowed by the
// current policy configuration.
func (s *EnrollmentService) IsMethodAllowed(method EnrollmentMethod) bool {
	for _, m := range s.config.EnrollmentMethods {
		if m == method {
			return true
		}
	}
	return false
}

// CleanExpiredCodes removes every expired, unconsumed one-time code from
// the store and reports how many were removed.
func (s *EnrollmentService) CleanExpiredCodes() (int, error) {
	removed, err := s.store.CleanExpiredCodes()
	if err != nil {
		return 0, &AgentError{Operation: "clean_expired_codes", Err: err}
	}
	return removed, nil
}

// RemoveAgent revokes the named agent's certificate through the CA and
// only then deletes its enrollment record. The certificate is always
// revoked before the record disappears: if revocation fails, the error is
// returned and the record is left in place so the agent remains rejectable
// on its next connection attempt and removal can be retried.
func (s *EnrollmentService) RemoveAgent(id string) error {
	if id == "" {
		return &AgentError{Operation: "remove_agent", Err: ErrInvalidRequestID}
	}

	info, err := s.store.GetAgent(id)
	if err != nil {
		return &AgentError{Operation: "remove_agent", Err: ErrAgentNotFound, Cause: err}
	}

	if info.CertificateSerial == "" {
		return &AgentError{Operation: "remove_agent", Err: ErrCertificateSerialMissing}
	}

	if err := s.ca.RevokeCertificate(info.CertificateSerial); err != nil {
		return &AgentError{Operation: "remove_agent", Err: ErrAgentRevocationFailed, Cause: err}
	}

	if err := s.store.DeleteAgent(id); err != nil {
		return &AgentError{Operation: "remove_agent", Err: err}
	}

	s.logger.Info("agent removed and certificate revoked",
		"agent_id", id, "serial", info.CertificateSerial)

	return nil
}

// VerifyAgentCertificate is the connection-time gate every agent
// certificate must pass before the mTLS handshake completes. It fails
// closed: any inability to determine enrollment or revocation status is
// treated as a rejection, never as an allow.
//
// Two independent checks both have to pass:
//   - the certificate's public key fingerprint matches an enrolled agent
//     that is still present in the store (a removed agent has no record,
//     so this alone rejects it regardless of revocation status);
//   - the certificate's serial number is not on the CA's revocation list.
func (s *EnrollmentService) VerifyAgentCertificate(cert *x509.Certificate) error {
	if cert == nil {
		return &AgentError{Operation: "verify_agent_certificate", Err: ErrCertificateInvalid}
	}

	id, err := publicKeyFingerprint(cert.PublicKey)
	if err != nil {
		return &AgentError{Operation: "verify_agent_certificate", Err: ErrCertificateInvalid, Cause: err}
	}

	if _, err := s.store.GetAgent(id); err != nil {
		return &AgentError{Operation: "verify_agent_certificate", Err: ErrAgentNotFound, Cause: err}
	}

	serial := cert.SerialNumber.Text(16)
	revoked, err := s.ca.IsRevoked(serial)
	if err != nil {
		return &AgentError{Operation: "verify_agent_certificate", Err: ErrRevocationCheckFailed, Cause: err}
	}
	if revoked {
		return &AgentError{Operation: "verify_agent_certificate", Err: ErrCertificateRevoked}
	}

	return nil
}

// checkMaxAgents checks whether the maximum enrolled agent limit has been
// reached. Returns nil if no limit is set or the limit has not been reached.
func (s *EnrollmentService) checkMaxAgents() error {
	if s.config.MaxAgents <= 0 {
		return nil
	}
	agents, err := s.store.ListAgents()
	if err != nil {
		return &AgentError{Operation: "check_max_agents", Err: err}
	}
	if len(agents) >= s.config.MaxAgents {
		return ErrMaxAgentsReached
	}
	return nil
}

// hashCode returns the hex-encoded SHA-256 hash of a one-time enrollment
// code. The store never sees the plaintext code, only this hash: a code
// carries enough entropy (generateSecureCode) that hashing it needs no
// salt to resist guessing, and a single equality comparison on the hash is
// exactly as strong a check as the plaintext comparison it replaces.
func hashCode(code string) string {
	sum := sha256.Sum256([]byte(code))
	return hex.EncodeToString(sum[:])
}

// generateSecureCode generates a cryptographically random hex string of
// the given length (in characters).
func generateSecureCode(length int) (string, error) {
	// Each byte produces 2 hex characters; round up.
	numBytes := (length + 1) / 2
	buf := make([]byte, numBytes)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return hex.EncodeToString(buf)[:length], nil
}

// csrFingerprint parses a PEM-encoded CSR and returns the SHA-256
// fingerprint of its public key in hex-encoded form. This is the same
// fingerprint an issued certificate's public key hashes to, so it doubles
// as the AgentInfo.ID that VerifyAgentCertificate looks up at connection
// time.
func csrFingerprint(csrPEM []byte) (string, error) {
	block, _ := pem.Decode(csrPEM)
	if block == nil {
		return "", ErrInvalidCSR
	}
	csr, err := x509.ParseCertificateRequest(block.Bytes)
	if err != nil {
		return "", ErrInvalidCSR
	}
	if err := csr.CheckSignature(); err != nil {
		return "", ErrInvalidCSR
	}
	fingerprint, err := publicKeyFingerprint(csr.PublicKey)
	if err != nil {
		return "", ErrInvalidCSR
	}
	return fingerprint, nil
}

// publicKeyFingerprint returns the SHA-256 fingerprint of a public key's
// SubjectPublicKeyInfo encoding, in hex-encoded form.
func publicKeyFingerprint(pub any) (string, error) {
	pubKeyBytes, err := x509.MarshalPKIXPublicKey(pub)
	if err != nil {
		return "", err
	}
	hash := sha256.Sum256(pubKeyBytes)
	return hex.EncodeToString(hash[:]), nil
}

// certificateSerialHex parses the leading PEM-encoded certificate in
// certPEM - the leaf the CA just issued - and returns its serial number
// hex-encoded with no leading zero padding (big.Int.Text(16)), matching
// the wire format xkmsd's RevokeCertificate and IsRevoked expect.
func certificateSerialHex(certPEM []byte) (string, error) {
	block, _ := pem.Decode(certPEM)
	if block == nil {
		return "", ErrCertificateInvalid
	}
	cert, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		return "", ErrCertificateInvalid
	}
	if cert.SerialNumber == nil {
		return "", ErrCertificateInvalid
	}
	return cert.SerialNumber.Text(16), nil
}
