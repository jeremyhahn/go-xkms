// testdata/devices_gui_fixture.yaml is byte-for-byte what the
// pre-#130(b) GUI phoneConfigDevice mirror produced: it was generated by
// marshaling sample data through that exact struct definition (field names,
// yaml tags and field order, including the per-device LastAttestation and
// AttestationPolicy blocks and the top-level attestation_policy's inline
// Rest map) before it was replaced by the alias to pairing.PairedDevice, so
// this test is pinned against the GUI's own historical output rather than
// against a hand-written approximation of it.
//
// Field ORDER is asserted semantically here, not byte-for-byte, and that is
// the one documented exception #130(b) allows. The pre-unification CLI and
// GUI structs already wrote two different, individually deterministic field
// orders for the same conceptual record — the CLI put device_boot_hash_hex
// right after last_device_attestation_time, the GUI put it after
// device_fingerprint — so no single unified struct can reproduce both
// writers' bytes at once. pairing.PairedDevice carries the CLI's order
// forward (see device_record_roundtrip_test.go for that byte-identical
// case); this test proves the GUI's file loses no data and no value across
// the reorder by comparing the parsed content of both documents instead of
// their raw bytes.
func TestPhoneConfigRoundTripsTheGUIFixtureContentIdentical(t *testing.T) {
	original, err := os.ReadFile("testdata/devices_gui_fixture.yaml")
	require.NoError(t, err)

	var cfg phoneConfig
	require.NoError(t, yaml.Unmarshal(original, &cfg))

	require.Len(t, cfg.Devices, 2)
	bound := cfg.Devices[0]
	assert.Equal(t, "Pixel 9 Pro Fold", bound.Name)
	assert.Equal(t, "AA:BB:CC:DD:EE:01", bound.Address)
	assert.Equal(t, "cGhvbmUtcHVibGljLWtleS1iYXNlNjQ=", bound.NoisePublicKey)
	assert.Equal(t, "bG9jYWwtcHJpdmF0ZS1rZXktYmFzZTY0", bound.LocalNoisePrivateKey)
	assert.True(t, bound.PairedAt.Equal(time.Date(2026, 3, 15, 10, 30, 0, 0, time.UTC)))
	assert.True(t, bound.LastDeviceAttestationTime.Equal(time.Date(2026, 3, 15, 10, 31, 5, 0, time.UTC)))
	assert.Equal(t, "strongbox", bound.SecurityLevel)
	assert.True(t, bound.BootStateVerified)
	assert.Equal(t, "aabbccddeeff00112233445566778899aabbccddeeff00112233445566778899", bound.DeviceFingerprint)
	assert.Equal(t, "deadbeefcafef00d", bound.DeviceBootHashHex)
	assert.Equal(t, 2, bound.AttestationProtocolVersion)
	assert.True(t, bound.IsBackend)

	require.NotNil(t, bound.LastAttestation, "the GUI-only field must survive the load")
	assert.True(t, bound.LastAttestation.Verified)
	assert.Equal(t, "strongbox", bound.LastAttestation.SecurityLevel)
	assert.Equal(t, "deadbeefcafef00d", bound.LastAttestation.BootHash)
	assert.Equal(t, "0011223344556677", bound.LastAttestation.BootKeyHash)
	assert.Equal(t, "verified", bound.LastAttestation.BootState)
	assert.True(t, bound.LastAttestation.DeviceLocked)
	assert.True(t, bound.LastAttestation.Timestamp.Equal(time.Date(2026, 4, 1, 9, 0, 0, 0, time.UTC)))

	require.NotNil(t, bound.AttestationPolicy, "the GUI-only field must survive the load")
	assert.True(t, bound.AttestationPolicy.Enabled)
	assert.Equal(t, "strongbox", bound.AttestationPolicy.SecurityLevel)
	// Fields the pre-unification CLI struct carried that this device's fixture
	// never set: round-tripping through the unified type must not invent them.
	assert.Zero(t, bound.AttestationGracePeriod)

	legacy := cfg.Devices[1]
	assert.Equal(t, "Legacy Phone", legacy.Name)
	assert.Zero(t, legacy.AttestationProtocolVersion)
	assert.Nil(t, legacy.LastAttestation)
	assert.Nil(t, legacy.AttestationPolicy)
	assert.False(t, legacy.IsBackend)

	require.NotNil(t, cfg.AttestationPolicy)
	assert.False(t, cfg.AttestationPolicy.AllowUnattestableDevices)
	assert.Equal(t, "5m0s", cfg.AttestationPolicy.Rest["default_grace_period"])
	assert.Equal(t, true, cfg.AttestationPolicy.Rest["require_device_attestation"])
	assert.Equal(t, "tee", cfg.AttestationPolicy.Rest["min_security_level"])

	resaved, err := yaml.Marshal(&cfg)
	require.NoError(t, err)

	var originalContent, resavedContent any
	require.NoError(t, yaml.Unmarshal(original, &originalContent))
	require.NoError(t, yaml.Unmarshal(resaved, &resavedContent))
	assert.Equal(t, originalContent, resavedContent,
		"every field the pre-unification GUI wrote must round-trip through the unified "+
			"type with the same value, even though the unified type's field order differs "+
			"from the GUI mirror's own order (see the field-order note above)")
}
