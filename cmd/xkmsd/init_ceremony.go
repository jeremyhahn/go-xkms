// Ceremony-execution error types. These wrap typed failure modes for the
// final phase of `xkmsd init` — constructing the in-process CA, executing
// the ceremony against it, and persisting the public artifacts the operator
// needs to bootstrap subsequent server runs.
var (
	// ErrCABackendCreateFailed is returned when the software key backend
	// that holds the CA's signing key cannot be constructed.
	ErrCABackendCreateFailed = errors.New("init: failed to create CA key backend")

	// ErrCAKeystoreCreateFailed is returned when the xkms keystore wrapper
	// around the CA key backend cannot be constructed.
	ErrCAKeystoreCreateFailed = errors.New("init: failed to create CA keystore")

	// ErrCACertStoreCreateFailed is returned when the CA certificate store
	// cannot be constructed.
	ErrCACertStoreCreateFailed = errors.New("init: failed to create CA certificate store")

	// ErrCAProfileRegistrationFailed is returned when a ceremony-required
	// certificate profile cannot be registered with the CA's profile registry.
	ErrCAProfileRegistrationFailed = errors.New("init: failed to register CA profile")

	// ErrCAConstructFailed is returned when ca.NewCA rejects the params
	// (typically because an identity field is missing or invalid).
	ErrCAConstructFailed = errors.New("init: failed to construct CA")

	// ErrCeremonyInitFailed is returned when CeremonyService.Initialize
	// rejects the request (CSR validation, share splitting, cert issuance).
	ErrCeremonyInitFailed = errors.New("init: ceremony initialization failed")

	// ErrAdminBundleWriteFailed is returned when the SO admin client bundle
	// cannot be written to its destination.
	ErrAdminBundleWriteFailed = errors.New("init: failed to write admin bundle")

	// ErrCABundleWriteFailed is returned when the CA bundle cannot be
	// persisted to the data directory.
	ErrCABundleWriteFailed = errors.New("init: failed to write CA bundle")

	// ErrSPKIPinWriteFailed is returned when the SPKI pin cannot be
	// persisted to the data directory.
	ErrSPKIPinWriteFailed = errors.New("init: failed to write SPKI pin")
)

// caCommonName is the Subject CN used for the CA generated by `xkmsd init`.
// The CN is intentionally fixed and operator-independent: the CA is the
// xkmsd trust root for issued operator / agent / TLS certificates, not the
// server's mTLS identity (that is handed out later via IssueCertificate).
const caCommonName = "xkmsd Root CA"

// defaultCAOrganization is the Organization carried on the CA subject when
// no operator-provided value exists. Used purely for human-readability of
// the issued certificates; the trust decision is bound to the SPKI pin.
const defaultCAOrganization = "xkms"

// ceremonyEnv bundles the runtime dependencies the ceremony-execution
// phase of `xkmsd init` needs. Constructed once by runInit and passed
// through so the helpers can be exercised in unit tests without going
// through os.Exit.
type ceremonyEnv struct {
	logger   *slog.Logger
	hostname string
	dataDir  string
	// adminBundlePath is the destination for the SO admin client bundle in
	// single-admin mode. The literal "-" means stdout (one-shot).
	adminBundlePath string
}

// executeCeremony constructs a software-backed CA, runs the ceremony
// against it, and persists the public artifacts (CA bundle, SPKI pin,
// admin bundle). The CA's signing key and certificate live in the same
// in-memory storage tier the rest of `xkmsd init` already uses — this
// command remains a one-shot bootstrap that emits the durable artifacts
// the operator needs while keeping any sealed material ephemeral by
// design (operators bring up the running server with `xkmsd run` against
// the artifacts written here).
//
// On success the helper returns the InitResult so callers can summarize
// the ceremony outcome.
func executeCeremony(
	ctx context.Context,
	cs *initialize.CeremonyService,
	env *ceremonyEnv,
) (*initialize.InitResult, error) {
	caInstance, err := newCeremonyCA(ctx, env)
	if err != nil {
		return nil, err
	}

	result, err := cs.Initialize(ctx, caInstance)
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCeremonyInitFailed, Err: err}
	}

	if err := persistCABundle(env.dataDir, result); err != nil {
		return nil, err
	}
	if err := persistSPKIPin(env.dataDir, result); err != nil {
		return nil, err
	}

	// Single-admin mode is the only path that returns an SO cert+key pair
	// during Initialize; M-of-N mode clears them in the wrapper because the
	// shares (and therefore the certs) are claimed asynchronously.
	if result.State == initialize.StateOperational && len(result.SOCertPEM) > 0 {
		if err := writeAdminBundle(env.adminBundlePath, result); err != nil {
			return nil, err
		}
	}

	return result, nil
}

// newCeremonyCA builds a fully initialized software-backed TrustedCA
// suitable for one-shot use during the `xkmsd init` ceremony. The CA
// uses ECDSA P-256 signing keys — the same default the production
// MultiIdentityCAConfig ships with — and stores everything in fresh
// in-memory backends so the helper is safe to run repeatedly and in
// parallel from unit tests. The profile registry is pre-populated with
// the ceremony-specific role profiles qrdb's CeremonyService relies on
// (custodian for M-of-N share enrollment, security-officer /
// administrator / operator / user / auditor for SignCSRInit) so the
// upstream ceremony can call SignCSR with these profile names without
// the default xkms registry returning ErrProfileNotFound.
func newCeremonyCA(ctx context.Context, env *ceremonyEnv) (ca.TrustedCA, error) {
	keyStorage := storage.NewMemory()
	swBackend, err := software.NewBackend(&software.Config{KeyStorage: keyStorage})
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCABackendCreateFailed, Err: err}
	}

	keystore, err := xkms.New(&xkms.BackendConfig{
		Backend:     swBackend,
		CertStorage: storage.NewMemory(),
	})
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCAKeystoreCreateFailed, Err: err}
	}

	certStore, err := certstore.New(&certstore.Config{
		CertStorage: storage.NewCertAdapter(storage.NewMemory()),
	})
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCACertStoreCreateFailed, Err: err}
	}

	profiles, err := newCeremonyProfileRegistry()
	if err != nil {
		return nil, err
	}

	identity := ca.Identity{
		Subject: ca.Subject{
			CommonName:   caCommonName,
			Organization: defaultCAOrganization,
		},
		Valid:         ca.DefaultRootValidityYears,
		Keys:          ca.DefaultKeyConfig(),
		KeystoreType:  types.StoreSoftware,
		IsRoot:        true,
		MaxPathLength: 1,
	}

	root, _, err := ca.NewCA(ctx, &ca.Params{
		Identity:  []ca.Identity{identity},
		KeyStore:  keystore,
		CertStore: certStore,
		Profiles:  profiles,
	})
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCAConstructFailed, Err: err}
	}

	_ = env // reserved for future per-hostname SANs on the CA cert
	return root, nil
}

// ceremonyProfileSpec describes a profile the upstream ceremony service
// needs to invoke by name. The set is derived from
// go-qrdb/pkg/ceremony/types.go (roleProfileMap) plus the literal
// "custodian" profile referenced by initializeMofN.
type ceremonyProfileSpec struct {
	name         string
	keyUsage     x509.KeyUsage
	extKeyUsage  []x509.ExtKeyUsage
	validityDays int
}

// ceremonyProfileSpecs is the canonical list of role profiles the
// ceremony issues against. Keeping it as package-level data — rather
// than threading the qrdb roleProfileMap across the module boundary —
// keeps the xkms CA self-contained.
var ceremonyProfileSpecs = []ceremonyProfileSpec{
	{
		name:         "custodian",
		keyUsage:     x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		extKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
		validityDays: 365,
	},
	{
		name:         "security-officer",
		keyUsage:     x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		extKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
		validityDays: 365,
	},
	{
		name:         "administrator",
		keyUsage:     x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		extKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
		validityDays: 365,
	},
	{
		name:         "operator",
		keyUsage:     x509.KeyUsageDigitalSignature,
		extKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
		validityDays: 180,
	},
	{
		name:         "user",
		keyUsage:     x509.KeyUsageDigitalSignature,
		extKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
		validityDays: 90,
	},
	{
		name:         "auditor",
		keyUsage:     x509.KeyUsageDigitalSignature,
		extKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
		validityDays: 180,
	},
}

// newCeremonyProfileRegistry returns a ProfileRegistry seeded with the
// xkms built-in profiles plus the ceremony-specific role profiles. The
// builder is the public surface for adding custom profiles, so the
// returned registry only differs from the default in the additional
// names — no behavior of the built-in profiles is changed.
func newCeremonyProfileRegistry() (ca.ProfileRegistry, error) {
	registry := ca.NewDefaultProfileRegistry()
	for _, spec := range ceremonyProfileSpecs {
		profile := ca.NewProfileBuilder(spec.name).
			WithKeyUsage(spec.keyUsage).
			WithExtKeyUsage(spec.extKeyUsage...).
			WithDefaultValidity(spec.validityDays).
			Build()
		if err := registry.Register(spec.name, profile); err != nil {
			return nil, &WrappedDetailError{Sentinel: ErrCAProfileRegistrationFailed, Detail: spec.name, Err: err}
		}
	}
	return registry, nil
}

// persistCABundle writes the CA bundle returned by the ceremony to
// "<dataDir>/ca-bundle.pem". The bundle is the canonical artifact other
// xkms processes pin against; persisting it here guarantees subsequent
// `xkmsd run` invocations and remote agents have a stable trust root.
func persistCABundle(dataDir string, result *initialize.InitResult) error {
	if len(result.CACertPEM) == 0 {
		return nil
	}
	if err := os.MkdirAll(dataDir, 0o700); err != nil {
		return &WrappedError{Sentinel: ErrCABundleWriteFailed, Err: err}
	}
	path := filepath.Join(dataDir, "ca-bundle.pem")
	if err := os.WriteFile(path, result.CACertPEM, 0o644); err != nil { //nolint:gosec // CA bundle is public material
		return &WrappedDetailError{Sentinel: ErrCABundleWriteFailed, Detail: path, Err: err}
	}
	return nil
}

// persistSPKIPin writes the hex-encoded SPKI pin to
// "<dataDir>/spki-pin.txt". The pin is the long-lived identifier clients
// use to verify the CA's identity even when the CA certificate has been
// rotated under the same key; emitting it as a separate file keeps the
// post-init operator workflow scriptable.
func persistSPKIPin(dataDir string, result *initialize.InitResult) error {
	if result.SPKIPin == "" {
		return nil
	}
	if err := os.MkdirAll(dataDir, 0o700); err != nil {
		return &WrappedError{Sentinel: ErrSPKIPinWriteFailed, Err: err}
	}
	path := filepath.Join(dataDir, "spki-pin.txt")
	if err := os.WriteFile(path, []byte(result.SPKIPin+"\n"), 0o644); err != nil { //nolint:gosec // SPKI pin is public material
		return &WrappedDetailError{Sentinel: ErrSPKIPinWriteFailed, Detail: path, Err: err}
	}
	return nil
}

// writeAdminBundle emits the SO admin client bundle (certificate + private
// key, both PEM-encoded) to the configured destination. The literal "-"
// directs the bundle to stdout; any other value is treated as a filesystem
// path. The bundle is a single concatenated PEM stream — cert first, then
// key — so it can be consumed unchanged by tooling that expects a combined
// client bundle (curl --cert, kubectl --client-certificate, etc.).
//
// The destination file is created with 0600 permissions because it
// contains a private key. Stdout is the canonical default per the
// `--admin-bundle` flag documentation; operators are expected to capture
// it once and discard the terminal output.
func writeAdminBundle(path string, result *initialize.InitResult) error {
	bundle := append(append([]byte{}, result.SOCertPEM...), result.SOKeyPEM...)
	if path == "" || path == "-" {
		return writeAdminBundleTo(os.Stdout, bundle)
	}
	// #nosec G304 -- path comes from operator-supplied flag during init
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o600)
	if err != nil {
		return &WrappedDetailError{Sentinel: ErrAdminBundleWriteFailed, Detail: path, Err: err}
	}
	defer func() { _ = f.Close() }()
	if err := writeAdminBundleTo(f, bundle); err != nil {
		return err
	}
	return nil
}

// writeAdminBundleTo streams the PEM bundle to w and wraps the io error
// in ErrAdminBundleWriteFailed. Split from writeAdminBundle so the same
// formatting path covers both the stdout and file destinations.
func writeAdminBundleTo(w io.Writer, bundle []byte) error {
	if _, err := w.Write(bundle); err != nil {
		return &WrappedError{Sentinel: ErrAdminBundleWriteFailed, Err: err}
	}
	return nil
}

// printCeremonyOutcome writes a human-readable summary of the ceremony
// outcome to stderr. The summary is informational only — the durable
// artifacts have already been written to dataDir / adminBundlePath when
// this is invoked.
func printCeremonyOutcome(env *ceremonyEnv, result *initialize.InitResult) {
	fmt.Fprintln(os.Stderr)
	fmt.Fprintln(os.Stderr, "=== xkmsd init: Ceremony Outcome ===")
	fmt.Fprintln(os.Stderr)
	fmt.Fprintf(os.Stderr, "  State:        %s\n", result.State)
	if result.SPKIPin != "" {
		fmt.Fprintf(os.Stderr, "  SPKI Pin:     %s\n", result.SPKIPin)
		fmt.Fprintf(os.Stderr, "  SPKI Pin File: %s\n", filepath.Join(env.dataDir, "spki-pin.txt"))
	}
	if len(result.CACertPEM) > 0 {
		fmt.Fprintf(os.Stderr, "  CA Bundle:    %s\n", filepath.Join(env.dataDir, "ca-bundle.pem"))
	}
	switch result.State {
	case initialize.StateOperational:
		if len(result.SOCertPEM) > 0 {
			dest := env.adminBundlePath
			if dest == "" || dest == "-" {
				dest = "stdout"
			}
			fmt.Fprintf(os.Stderr, "  Admin Bundle: %s (cert+key, 0600 if on-disk)\n", dest)
		}
	case initialize.StateEnrolling:
		fmt.Fprintf(os.Stderr, "  Shares:       %d Shamir shares generated; run\n", result.ShareCount)
		fmt.Fprintln(os.Stderr, "                `xkmsctl init claim-cert` then `xkmsctl init claim-share`")
		fmt.Fprintln(os.Stderr, "                from each officer host to enroll.")
	}
	fmt.Fprintln(os.Stderr)
}
