// Ceremony-execution error types. These wrap typed failure modes for the
// final phase of `xkmsd init` — constructing the in-process CA, executing
// the ceremony against it, and persisting the public artifacts the operator
// needs to bootstrap subsequent server runs.
var (
	// ErrCABackendCreateFailed is returned when the software key backend
	// that holds the CA's signing key cannot be constructed.
	ErrCABackendCreateFailed = errors.New("init: failed to create CA key backend")

	// ErrCAKeystoreCreateFailed is returned when the xkms keystore wrapper
	// around the CA key backend cannot be constructed.
	ErrCAKeystoreCreateFailed = errors.New("init: failed to create CA keystore")

	// ErrCACertStoreCreateFailed is returned when the CA certificate store
	// cannot be constructed.
	ErrCACertStoreCreateFailed = errors.New("init: failed to create CA certificate store")

	// ErrCAConstructFailed is returned when ca.NewCA rejects the params
	// (typically because an identity field is missing or invalid).
	ErrCAConstructFailed = errors.New("init: failed to construct CA")

	// ErrCABundleReadFailed is returned when the CA's bundle or certificate
	// cannot be read to derive the public artifacts.
	ErrCABundleReadFailed = errors.New("init: failed to read the CA bundle")

	// ErrCABundleWriteFailed is returned when the CA bundle cannot be
	// persisted to the data directory.
	ErrCABundleWriteFailed = errors.New("init: failed to write CA bundle")

	// ErrSPKIPinWriteFailed is returned when the SPKI pin cannot be
	// persisted to the data directory.
	ErrSPKIPinWriteFailed = errors.New("init: failed to write SPKI pin")

	// ErrFirstBootFailed is returned when qrdb's canonical first-boot
	// bootstrap (system tenant, roles, administrator) fails against the
	// durable node this ceremony opened.
	ErrFirstBootFailed = errors.New("init: first-boot against the durable node failed")

	// ErrAdminCredentialPersistFailed is returned when the administrator's
	// certificate and key cannot be written to the data directory.
	ErrAdminCredentialPersistFailed = errors.New("init: failed to persist the administrator credential")

	// ErrAdminUserResolveFailed is returned when the administrator's durable
	// user record cannot be resolved after first-boot, so no admin factor can
	// be attached to a userID.
	ErrAdminUserResolveFailed = errors.New("init: failed to resolve the administrator's durable user record")

	// ErrServiceContextFailed is returned when the durable node cannot bind
	// its service principal, which the administrator lookup and factor
	// persistence run as.
	ErrServiceContextFailed = errors.New("init: failed to bind the durable node's service principal")

	// ErrUserAuthFactorsUnavailable is returned when the durable node's
	// client exposes no user-side auth-factor transport to persist admin
	// factors through.
	ErrUserAuthFactorsUnavailable = errors.New("init: durable node exposes no user auth-factor transport")
)

// caCommonName is the Subject CN used for the CA generated by `xkmsd init`.
// The CN is intentionally fixed and operator-independent: the CA is the
// xkmsd trust root for issued operator / agent / TLS certificates, not the
// server's mTLS identity (that is handed out later via IssueCertificate).
const caCommonName = "xkmsd Root CA"

// defaultCAOrganization is the Organization carried on the CA subject when
// no operator-provided value exists. Used purely for human-readability of
// the issued certificates; the trust decision is bound to the SPKI pin.
const defaultCAOrganization = "xkms"

// ceremonyEnv bundles the runtime dependencies the bootstrap phase of
// `xkmsd init` needs. Constructed once by runInit and passed
// through so the helpers can be exercised in unit tests without going
// through os.Exit.
type ceremonyEnv struct {
	logger   *slog.Logger
	hostname string
	dataDir  string

	// enrollmentPlan is the ordered set of login factors to enroll for the
	// administrator (--admin-factor). Nil means the mTLS baseline.
	enrollmentPlan *qrdbsdk.AdminEnrollmentPlan

	// passkeyDevice selects one FIDO2 authenticator when several are
	// attached (--passkey-device).
	passkeyDevice string

	// passkeyPIN is the CTAP2 PIN of the authenticator being enrolled
	// (--passkey-pin-stdin / XKMS_PASSKEY_PIN). Nil when the key has none.
	passkeyPIN *secure.Secret

	// relyingPartyID / relyingPartyName scope an enrolled passkey to the
	// domain the console is served from.
	relyingPartyID   string
	relyingPartyName string

	// fido2Handler drives an attached authenticator. Nil when this build or
	// host has no FIDO2 support.
	fido2Handler *pkgfido2.FIDO2Handler

	// enrolledFactors records what the ceremony enrolled, for the summary.
	enrolledFactors []qrdbsdk.AdminEnrollmentResult

	// nodeCfg is the deployment configuration the durable qrdb node is opened
	// with on the single-admin path (see resolveInitNodeConfig). It resolves
	// an IDENTICAL storage+seal shape to the one `xkmsd run` will resolve from
	// the same operator config, so the two opens of one Pebble directory never
	// disagree about the database engine or the barrier/seal configuration.
	nodeCfg *config.Config

	// soPin is the Security Officer PIN (--so-pin), reused here as the node
	// barrier's operator-present unseal credential for "passphrase" (see
	// unsealDurableInitNode) -- the same credential the operator already
	// supplied to run this ceremony at all.
	soPin []byte

	// persister writes each enrolled admin factor into the durable node's
	// auth-factor store, resolved once the ceremony has opened that node and
	// run first-boot (see executeCeremony). Nil until then, which preserves
	// probe-only behaviour (enroll and report, persist nothing) for the paths
	// that never reach the durable store -- M-of-N mode, and any failure
	// before the node's admin user is resolved.
	persister qrdbsdk.AdminFactorPersister

	// adminUserID is the durable node's numeric userID for the administrator
	// first-boot created (or found already existing), set alongside
	// persister. Zero until then. Exposed on env mainly so tests can verify
	// persisted state directly against the node without re-deriving the
	// userID from a certificate thumbprint.
	adminUserID uint64

	// adminCertPEM is the administrator's client certificate as issued by
	// first-boot, threaded into the mtls factor's enrollment inputs so
	// `--admin-factor mtls` has a certificate to bind.
	adminCertPEM []byte
}

// adminUsername is the administrator identity the ceremony enrolls factors
// against.
const adminUsername = "administrator"

// systemTenantID scopes the bootstrap administrator.
const systemTenantID = "system"

// bootstrapResult is the public outcome of the bootstrap: the CA bundle and
// SPKI pin first-contact clients verify against.
type bootstrapResult struct {
	// CABundlePEM is the PEM-encoded CA bundle.
	CABundlePEM []byte

	// SPKIPin is the hex-encoded SHA-256 of the CA certificate's
	// SubjectPublicKeyInfo.
	SPKIPin string
}

// executeBootstrap constructs a software-backed CA, persists its public
// artifacts (CA bundle, SPKI pin), and bootstraps the durable node's
// administrator against it. The CA's signing key and certificate live in the
// same in-memory storage tier the rest of `xkmsd init` uses -- this command
// remains a one-shot bootstrap that emits the durable artifacts the operator
// needs while keeping any sealed material ephemeral by design (operators
// bring up the running server with `xkmsd run` against the artifacts written
// here).
//
// On success the helper returns the bootstrapResult so callers can summarize
// the outcome.
func executeBootstrap(ctx context.Context, env *ceremonyEnv) (*bootstrapResult, error) {
	caInstance, err := newBootstrapCA(ctx, env, dao.NewStoreFactory(qrdbsdk.NewMemoryKVStore()))
	if err != nil {
		return nil, err
	}

	result, err := caArtifacts(caInstance)
	if err != nil {
		return nil, err
	}

	if err := persistCABundle(env.dataDir, result); err != nil {
		return nil, err
	}
	if err := persistSPKIPin(env.dataDir, result); err != nil {
		return nil, err
	}

	// The SO identity is CSR-based; the server never holds holder private
	// keys, so there is no credential bundle to write.
	if err := bootstrapDurableAdmin(ctx, caInstance, env); err != nil {
		return nil, err
	}

	return result, nil
}

// caArtifacts reads the CA's public bundle and certificate and derives the
// SPKI pin from the latter.
func caArtifacts(caInstance initialize.CeremonyCA) (*bootstrapResult, error) {
	bundle, err := caInstance.CABundle()
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCABundleReadFailed, Err: err}
	}
	cert, err := caInstance.CACertificate()
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCABundleReadFailed, Err: err}
	}
	return &bootstrapResult{CABundlePEM: bundle, SPKIPin: initialize.SPKIPin(cert)}, nil
}

// bootstrapDurableAdmin opens the durable qrdb node `xkmsd run` will later
// reopen from the same data directory, runs qrdb's canonical first-boot
// against it (system tenant, roles, the administrator and its CA-issued
// certificate), wires env's factor persister to that node's auth-factor
// store, and enrolls the planned admin login factors against it -- all while
// the node is open, since the persister writes through the SAME node client
// enrollAdminFactors uses.
//
// The node is always closed before this returns, success or failure, so
// `xkmsd run` can reopen the same Pebble directory afterward; a close failure
// is logged rather than returned, since by the time Close runs the ceremony's
// durable work (first-boot, credential file, persisted factors) has already
// committed and a close error must not make that success look like a
// failure.
func bootstrapDurableAdmin(ctx context.Context, caInstance initialize.CeremonyCA, env *ceremonyEnv) error {
	node, sealRes, err := openDurableInitNode(ctx, env.nodeCfg, env.logger)
	if err != nil {
		return err
	}
	defer func() {
		if cerr := node.Close(); cerr != nil {
			env.logger.Warn("init: failed to close the durable qrdb node", slog.Any("error", cerr))
		}
	}()

	strategy := env.nodeCfg.Barrier.SealStrategy()
	if err := unsealDurableInitNode(ctx, node, sealRes, strategy, env.soPin); err != nil {
		return err
	}

	fbResult, err := xkmsserver.RunFirstBoot(ctx, node, xkmsserver.FirstBootParams{
		CA:          caInstance,
		TrustDomain: embeddednode.TrustDomain(env.nodeCfg),
		Logger:      env.logger,
	})
	if err != nil {
		return &WrappedError{Sentinel: ErrFirstBootFailed, Err: err}
	}
	if err := xkmsserver.PersistAdminCredential(env.dataDir, fbResult, env.logger); err != nil {
		return &WrappedError{Sentinel: ErrAdminCredentialPersistFailed, Err: err}
	}

	// Resolving the administrator and persisting its factors is xkms's own
	// work, so it runs as the node's service principal; the embedded client
	// refuses a bare context.
	serviceprincipal.RegisterCeremonyGrant()
	svcCtx, err := node.ServiceContext(ctx)
	if err != nil {
		return &WrappedError{Sentinel: ErrServiceContextFailed, Err: err}
	}

	adminUser, err := node.Client().Users().GetUserByCertThumbprint(svcCtx, fbResult.AdminCertThumbprint)
	if err != nil {
		return &WrappedError{Sentinel: ErrAdminUserResolveFailed, Err: err}
	}

	factorsClient := node.Client().UserAuthFactors()
	if factorsClient == nil {
		return ErrUserAuthFactorsUnavailable
	}

	env.adminCertPEM = fbResult.AdminCertPEM
	env.adminUserID = adminUser.ID
	env.persister = &nodeFactorPersister{client: factorsClient, userID: adminUser.ID}

	return enrollAdminFactors(svcCtx, env)
}

// newBootstrapCA builds a fully initialized software-backed TrustedCA
// suitable for one-shot use during the `xkmsd init` ceremony. The CA
// uses ECDSA P-256 signing keys — the same default the production
// MultiIdentityCAConfig ships with — keeps its keys in fresh in-memory
// backends, and stores its certificates as DAO entities in the
// certstore.DatabaseName database daos serves, so the helper is safe to run
// repeatedly and in parallel from unit tests. The profile registry is pre-populated with
// the ceremony-specific role profiles qrdb's CeremonyService relies on
// (custodian for M-of-N share enrollment, security-officer /
// administrator / operator / user / auditor for SignCSRInit) so the
// upstream ceremony can call SignCSR with these profile names without
// the default xkms registry returning ErrProfileNotFound.
func newBootstrapCA(ctx context.Context, env *ceremonyEnv, daos *qrdbsdk.DAOFactory) (initialize.CeremonyCA, error) {
	keyStorage := storage.NewMemory()
	swBackend, err := software.NewBackend(&software.Config{KeyStorage: keyStorage})
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCABackendCreateFailed, Err: err}
	}

	keystore, err := xkms.New(&xkms.BackendConfig{
		Backend:     swBackend,
		CertStorage: storage.NewMemory(),
	})
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCAKeystoreCreateFailed, Err: err}
	}

	certStore, err := certstore.New(&certstore.Config{DAOs: daos})
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCACertStoreCreateFailed, Err: err}
	}

	identity := ca.Identity{
		Subject: ca.Subject{
			CommonName:   caCommonName,
			Organization: defaultCAOrganization,
		},
		Valid:         ca.DefaultRootValidityYears,
		Keys:          ca.DefaultKeyConfig(),
		IsRoot:        true,
		MaxPathLength: 1,
	}

	// The ceremony CA is software-only (a single in-memory backend for its
	// one key), so BackendForStore trivially returns that backend for every
	// StoreType.
	backendForStore := func(string, types.StoreType) (xkms.Backend, error) {
		return keystore, nil
	}

	root, _, err := ca.NewCA(ctx, &ca.Params{
		Identity:        []ca.Identity{identity},
		KeyStore:        keystore,
		CertStore:       certStore,
		Profiles:        ca.NewDefaultProfileRegistry(),
		BackendForStore: backendForStore,
		RevocationStore: storage.NewMemory(),
	})
	if err != nil {
		return nil, &WrappedError{Sentinel: ErrCAConstructFailed, Err: err}
	}

	_ = env // reserved for future per-hostname SANs on the CA cert
	return root, nil
}

// persistCABundle writes the CA bundle returned by the ceremony to
// "<dataDir>/ca-bundle.pem". The bundle is the canonical artifact other
// xkms processes pin against; persisting it here guarantees subsequent
// `xkmsd run` invocations and remote agents have a stable trust root.
func persistCABundle(dataDir string, result *bootstrapResult) error {
	if len(result.CABundlePEM) == 0 {
		return nil
	}
	if err := os.MkdirAll(dataDir, 0o700); err != nil {
		return &WrappedError{Sentinel: ErrCABundleWriteFailed, Err: err}
	}
	path := filepath.Join(dataDir, "ca-bundle.pem")
	if err := os.WriteFile(path, result.CABundlePEM, 0o644); err != nil { // #nosec G306 -- CA bundle is public material
		return &WrappedDetailError{Sentinel: ErrCABundleWriteFailed, Detail: path, Err: err}
	}
	return nil
}

// persistSPKIPin writes the hex-encoded SPKI pin to
// "<dataDir>/spki-pin.txt". The pin is the long-lived identifier clients
// use to verify the CA's identity even when the CA certificate has been
// rotated under the same key; emitting it as a separate file keeps the
// post-init operator workflow scriptable.
func persistSPKIPin(dataDir string, result *bootstrapResult) error {
	if result.SPKIPin == "" {
		return nil
	}
	if err := os.MkdirAll(dataDir, 0o700); err != nil {
		return &WrappedError{Sentinel: ErrSPKIPinWriteFailed, Err: err}
	}
	path := filepath.Join(dataDir, "spki-pin.txt")
	if err := os.WriteFile(path, []byte(result.SPKIPin+"\n"), 0o644); err != nil { // #nosec G306 -- SPKI pin is public material
		return &WrappedDetailError{Sentinel: ErrSPKIPinWriteFailed, Detail: path, Err: err}
	}
	return nil
}

// printCeremonyOutcome writes a human-readable summary of the ceremony
// outcome to stderr. The summary is informational only — the durable
// artifacts have already been written to dataDir when this is invoked.
// printEnrolledFactors lists the administrator's login credentials so the
// operator knows exactly what they can sign in with — and, on a partial
// failure, what they cannot.
func printEnrolledFactors(env *ceremonyEnv) {
	if len(env.enrolledFactors) == 0 {
		return
	}
	names := make([]string, 0, len(env.enrolledFactors))
	for _, e := range env.enrolledFactors {
		names = append(names, e.Factor.String())
	}
	fmt.Fprintf(os.Stderr, "  Login factors: %s\n", strings.Join(names, ", "))
}

func printBootstrapOutcome(env *ceremonyEnv, result *bootstrapResult) {
	defer printEnrolledFactors(env)
	fmt.Fprintln(os.Stderr)
	fmt.Fprintln(os.Stderr, "=== xkmsd init: Bootstrap Outcome ===")
	fmt.Fprintln(os.Stderr)
	if result.SPKIPin != "" {
		fmt.Fprintf(os.Stderr, "  SPKI Pin:     %s\n", result.SPKIPin)
		fmt.Fprintf(os.Stderr, "  SPKI Pin File: %s\n", filepath.Join(env.dataDir, "spki-pin.txt"))
	}
	if len(result.CABundlePEM) > 0 {
		fmt.Fprintf(os.Stderr, "  CA Bundle:    %s\n", filepath.Join(env.dataDir, "ca-bundle.pem"))
	}
	fmt.Fprintln(os.Stderr)
}

// adminEnrollmentConfig projects the ceremony environment onto the reusable
// go-xkms admin-enrollment orchestration (pkg/init/admin_enrollment.go). The
// registry construction, hardware preflight, and enrollment all live there so
// every project embedding go-qrdb through go-xkms performs them identically;
// xkmsd is just its first consumer.
func adminEnrollmentConfig(env *ceremonyEnv) initialize.AdminEnrollmentConfig {
	return initialize.AdminEnrollmentConfig{
		Plan:             env.enrollmentPlan,
		Username:         adminUsername,
		DisplayName:      adminUsername,
		TenantID:         systemTenantID,
		RelyingPartyID:   env.relyingPartyID,
		RelyingPartyName: env.relyingPartyName,
		PasskeyDevice:    env.passkeyDevice,
		PasskeyPIN:       env.passkeyPIN,
		FIDO2Handler:     env.fido2Handler,
		AdminCertPEM:     env.adminCertPEM,
		// Persister is nil until executeCeremony has opened the durable node
		// and run first-boot (single-admin path only); a nil persister
		// preserves probe-only behaviour -- enroll and report, persist
		// nothing -- for M-of-N mode and for preflight, which must never
		// write anything.
		Persister: env.persister,
	}
}

// preflightAdminFactors refuses the ceremony before it changes any state when
// a planned factor cannot succeed.
func preflightAdminFactors(ctx context.Context, env *ceremonyEnv) error {
	return initialize.PreflightAdminFactors(ctx, adminEnrollmentConfig(env))
}

// enrollAdminFactors runs the planned login factors for the administrator the
// ceremony just created.
func enrollAdminFactors(ctx context.Context, env *ceremonyEnv) error {
	enrolled, err := initialize.EnrollAdminFactors(ctx, adminEnrollmentConfig(env))
	// Report what IS live even on failure, so an operator is not left guessing
	// whether the administrator has any usable credential.
	for _, e := range enrolled {
		env.logger.Info("admin login factor enrolled", slog.String("factor", e.Factor.String()))
	}
	if err != nil {
		return err
	}
	env.enrolledFactors = enrolled
	return nil
}
