// TestXKeySoftwarePIVKeyOutlivesTheProcess generates a software PIV key
// with one xkey process and signs a CSR with it in another: the key lives in
// xKey's key store, encrypted at rest by the barrier, not in the memory of
// the process that generated it.
func TestXKeySoftwarePIVKeyOutlivesTheProcess(t *testing.T) {
	const password = "piv-key-store-pw"
	home := t.TempDir()
	vars := append(xkeyHome(home), "XKEY_BARRIER_PASSWORD="+password)

	out, err := runXKey(vars, password+"\n"+password+"\n", "barrier", "init", "--strategy", "software")
	require.NoError(t, err, out)

	out, err = runXKey(vars, "", "piv", "generate", "9a", "--backend", "software", "--pin-policy", "never")
	require.NoError(t, err, out)
	generated := pemBlockAfter(t, out, "PUBLIC KEY")

	csrFile := filepath.Join(home, "piv.csr")
	out, err = runXKey(vars, "", "piv", "csr", "9a", "--backend", "software", "--cn", "piv-user", "--output", csrFile)
	require.NoError(t, err, "a later process signs with the generated key:\n%s", out)

	data, err := os.ReadFile(csrFile)
	require.NoError(t, err)
	block, _ := pem.Decode(data)
	require.NotNil(t, block)
	csr, err := x509.ParseCertificateRequest(block.Bytes)
	require.NoError(t, err)
	require.NoError(t, csr.CheckSignature())
	der, err := x509.MarshalPKIXPublicKey(csr.PublicKey)
	require.NoError(t, err)
	assert.Equal(t, generated, der, "the CSR carries the key generated by the first process")

	keysDir := filepath.Join(home, "data")
	assert.NotContains(t, readTree(t, keysDir), "PRIVATE KEY", "no private key is stored in plaintext")
}

// pemBlockAfter returns the DER of the first PEM block of type in out.
func pemBlockAfter(t *testing.T, out, blockType string) []byte {
	t.Helper()
	start := strings.Index(out, "-----BEGIN "+blockType+"-----")
	require.GreaterOrEqual(t, start, 0, "no %s in:\n%s", blockType, out)
	block, _ := pem.Decode([]byte(out[start:]))
	require.NotNil(t, block)
	return block.Bytes
}

// readTree concatenates every regular file under dir.
func readTree(t *testing.T, dir string) string {
	t.Helper()
	var all strings.Builder
	require.NoError(t, filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		data, readErr := os.ReadFile(path)
		if readErr != nil {
			return readErr
		}
		all.Write(data)
		return nil
	}))
	return all.String()
}
